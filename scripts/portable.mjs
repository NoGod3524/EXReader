import { cp, mkdir, writeFile, readFile, readdir } from 'node:fs/promises';
import { zipSync, strToU8 } from 'fflate';
if (process.platform !== 'win32') throw new Error('This packaging script produces the Windows portable release. Use tauri build for macOS/Linux.');
const folder = 'release/EXReader-portable';
await mkdir(folder, { recursive: true });
const exe = await readFile('src-tauri/target/release/exreader.exe');
const instructions = 'EXReader 0.1.0\r\n\r\n解压后双击 EXReader.exe。需要 Windows 10/11 与系统 WebView2 运行时。\r\n.portable 标记存在时，书库保存在程序旁 EXReader-data 文件夹。\r\n更新时保留该文件夹；迁移前请在设置中备份书库。\r\n复杂格式转换需另装 calibre，或将它放在程序旁的 calibre 文件夹。\r\n';
await cp('src-tauri/target/release/exreader.exe', `${folder}/EXReader.exe`);
await writeFile(`${folder}/.portable`, '');
await writeFile(`${folder}/使用说明.txt`, '\ufeff' + instructions);
const license = await readFile('LICENSE');
const notices = await readFile('THIRD_PARTY_NOTICES.md');
const readme = await readFile('README.md');
await writeFile(`${folder}/LICENSE`, license);
await writeFile(`${folder}/THIRD_PARTY_NOTICES.md`, notices);
await writeFile(`${folder}/功能与构建说明.md`, readme);
await cp('public/licenses', `${folder}/licenses`, { recursive: true });
const entries = { 'EXReader-portable/EXReader.exe': exe, 'EXReader-portable/.portable': strToU8(''), 'EXReader-portable/使用说明.txt': strToU8('\ufeff' + instructions), 'EXReader-portable/LICENSE': license, 'EXReader-portable/THIRD_PARTY_NOTICES.md': notices };
entries['EXReader-portable/功能与构建说明.md'] = readme;
for (const name of await readdir('public/licenses')) entries[`EXReader-portable/licenses/${name}`] = await readFile(`public/licenses/${name}`);
const zipped = zipSync(entries);
await writeFile('release/EXReader-Windows-x64-portable.zip', zipped);
console.log('Windows portable:', (exe.length / 1024 / 1024).toFixed(1), 'MB executable');
