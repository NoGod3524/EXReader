/* Both locale tables must stay parallel to rl_messages, and the row count must
   match RL_MESSAGE_COUNT, which sizes the digest index array. The typedef fails
   to compile when a row is added to one table and not the others. */
typedef char rl_catalog_tables_parallel[
    (sizeof(rl_zh_templates) / sizeof(rl_zh_templates[0]) == sizeof(rl_messages) / sizeof(rl_messages[0]) &&
     sizeof(rl_en_templates) / sizeof(rl_en_templates[0]) == sizeof(rl_messages) / sizeof(rl_messages[0]) &&
     sizeof(rl_messages) / sizeof(rl_messages[0]) == (size_t)RL_MESSAGE_COUNT)
        ? 1 : -1];
