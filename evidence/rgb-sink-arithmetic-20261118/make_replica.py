sub('bilinear_sample(b->pixels+(size_t)y.first*b->stride,b->pixels+(size_t)y.second*b->stride,x,y.fraction,out);',
    'bilinear_sample(b->pixels+(size_t)REPLICA_ROW(y.first)*b->stride,b->pixels+(size_t)REPLICA_ROW(y.second)*b->stride,x,y.fraction,out);')
sub('p=b->pixels+(size_t)y*b->stride+x*4;\n  out[3]=p[3];','p=b->pixels+(size_t)REPLICA_ROW(y)*b->stride+x*4;\n  out[3]=p[3];')
sub('q=mask->pixels+(size_t)y*mask->stride+x*4;','q=mask->pixels+(size_t)REPLICA_ROW(y)*mask->stride+x*4;')
sub('for(k=0;k<2;k++) line[k]=ry[k]<0 ? NULL : b->pixels+(size_t)ry[k]*b->stride;',
    'for(k=0;k<2;k++) line[k]=ry[k]<0 ? NULL : b->pixels+(size_t)REPLICA_ROW(ry[k])*b->stride;')
