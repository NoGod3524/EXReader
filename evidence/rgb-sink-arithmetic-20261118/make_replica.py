"""Derive replica.c from src/affine_image.c by exact, counted text substitutions.

The production file is never edited. Every substitution must match the expected
number of times, so a renderer change makes this script fail instead of silently
measuring different code. With REPLICA_ID 0 (mask 0) every substituted expression
reduces to the production expression; capture.py checks byte-identical output.
"""
from pathlib import Path
import hashlib,sys
HERE=Path(__file__).resolve().parent
ROOT=HERE.parent.parent
SOURCE=ROOT/'src/affine_image.c'
text=SOURCE.read_text(encoding='utf-8').replace('\r\n','\n')
source_sha=hashlib.sha256(text.encode()).hexdigest()

def sub(old,new,count=1):
    global text
    found=text.count(old)
    if found!=count: sys.exit(f'Expected {count} match(es), found {found}: {old[:70]!r}')
    text=text.replace(old,new)

PRELUDE='''#include "replica_knobs.h"
'''
