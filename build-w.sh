#!/usr/bin/env bash
set -e
cd -- "$(dirname -- "$0")"
cmake -S . -B build/w -G Ninja \
    -DCMAKE_BUILD_TYPE=Release -DCMAKE_C_COMPILER=gcc -DCMAKE_CXX_COMPILER=g++ \
    -DEXR_BUILD_FUZZ=OFF -DEXR_BUILD_JNI=OFF -DEXR_BUILD_SHARED_COMPAT=ON \
    -DEXR_BUILD_TESTS=ON -DEXR_BUILD_TEXT_INDEX=ON -DEXR_BUILD_TOOLS=ON \
    -DEXR_ENABLE_AAC=OFF -DEXR_ENABLE_AUDIO=ON -DEXR_ENABLE_ICC=OFF \
    -DEXR_ENABLE_IMAGE_AVIF=OFF -DEXR_ENABLE_IMAGE_TIFF=OFF -DEXR_ENABLE_IMAGE_WEBP=OFF \
    -DEXR_ENABLE_LIBRARY=ON -DEXR_ENABLE_MP3=OFF -DEXR_ENABLE_PDF=ON \
    -DEXR_ENABLE_PDF_CRYPTO=OFF -DEXR_ENABLE_PDF_EDIT=ON -DEXR_ENABLE_PDF_JPX=ON \
    -DEXR_ENABLE_TEXT_INDEX=ON -DEXR_SANITIZE=OFF \
    -DCMAKE_PROJECT_EXReader_INCLUDE="$PWD/examples/windows/selection_tests.cmake" \
    "$@" > build-config.log 2>&1
cmake --build build/w > build-w.log 2>&1
