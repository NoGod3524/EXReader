"""Exercise stale literals and all three evidence obligations without rebuilding SDKs."""
from contextlib import redirect_stdout
import io
import json
from pathlib import Path
import sys
from tempfile import TemporaryDirectory

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'tools'))
import check_version_consistency as guard


def check_archive_scope(root):
    major, minor, patch = map(int, guard.source_version(root).split('.'))
    data = f'find_package(EXReader {major}.{minor - 1}.{patch} EXACT CONFIG REQUIRED)\n'
    (root / 'archive').mkdir(exist_ok=True)
    with TemporaryDirectory(prefix='version-scope-', dir=root / 'archive') as archived:
        snapshot = Path(archived) / 'CMakeLists.txt'
        snapshot.write_text(data, encoding='utf-8')
        assert snapshot.relative_to(root).as_posix() in guard.tracked(root)
        output = io.StringIO()
        with redirect_stdout(output):
            assert not guard.check(root), output.getvalue()
        print('PASS: archive historical consumer excluded by path')
        with TemporaryDirectory(prefix='version-scope-', dir=root / 'tests') as current:
            consumer = Path(current) / 'CMakeLists.txt'
            consumer.write_bytes(snapshot.read_bytes())
            name = consumer.relative_to(root).as_posix()
            assert name in guard.tracked(root)
            output = io.StringIO()
            with redirect_stdout(output):
                assert guard.check(root), 'current consumer mismatch accepted'
            assert name + ':1' in output.getvalue(), output.getvalue()
            print(output.getvalue(), end='')
            print('PASS: identical current consumer mismatch rejected')


def main():
    root = guard.ROOT
    path = root / guard.MANIFEST
    original = path.read_bytes()
    entries = json.loads(original)
    cases = 0
    try:
        output = io.StringIO()
        with redirect_stdout(output):
            assert not guard.check(root)
        for kind in ('stale-line', 'changed-literal', 'frozen-bytes', 'migration-reference',
                     'migration-removal', 'negative-assertion', 'duplicate'):
            rows = json.loads(original)
            entry = next(item for item in rows if item['purpose'] == {
                'frozen-bytes': 'frozen_baseline', 'migration-reference': 'migration_compat',
                'migration-removal': 'migration_compat', 'negative-assertion': 'negative_case'
            }.get(kind, 'frozen_baseline'))
            if kind == 'stale-line':
                entry['line'] = 10**9
            elif kind == 'changed-literal':
                entry['literal'] = '9.99.99'
            elif kind == 'frozen-bytes':
                entry['frozen_object']['sha256'] = '0' * 64
            elif kind == 'migration-reference':
                entry['migration_test']['invocation']['sha256'] = '0' * 64
            elif kind == 'migration-removal':
                entry['migration_test']['removal_condition'] = ''
            elif kind == 'negative-assertion':
                entry['rejection_assertion']['sha256'] = '0' * 64
            else:
                rows.append(dict(entry))
            path.write_text(json.dumps(rows), encoding='utf-8')
            output = io.StringIO()
            with redirect_stdout(output):
                assert guard.check(root), kind + ': invalid evidence accepted'
            assert f'{entry["file"]}:{entry["line"]}' in output.getvalue(), output.getvalue()
            cases += 1
            print('PASS: reject ' + kind)
    finally:
        path.write_bytes(original)
    template = root / 'cmake/version.h.in'
    header = root / 'include/exr/version.h'
    readme = root / 'README.md'
    originals = {p: p.read_bytes() for p in (template, header, readme)}
    try:
        guard.sync(root)
        assert header.read_bytes() == originals[header], 'unchanged regeneration changed header bytes'
        assert readme.read_bytes() == originals[readme], 'unchanged regeneration changed README bytes'
        print('PASS: unchanged regeneration is byte-identical (header and README)')
        template.write_bytes(originals[template] + b'/* template drift probe */\n')
        output = io.StringIO()
        with redirect_stdout(output):
            assert guard.check(root), 'template drift accepted'
        assert 'include/exr/version.h:1' in output.getvalue(), output.getvalue()
        print(output.getvalue(), end='')
        guard.sync(root)
        assert header.read_bytes() != originals[header], 'template change did not change generated bytes'
        print('PASS: template change changes generated bytes and is rejected before sync')
        template.write_bytes(originals[template])
        header.write_bytes(originals[header].replace(b'\n', b'\r\n'))
        output = io.StringIO()
        with redirect_stdout(output):
            assert guard.check(root), 'newline-only generated drift accepted'
        assert 'include/exr/version.h:1' in output.getvalue(), output.getvalue()
        print('PASS: newline-only generated drift rejected')
    finally:
        for target, data in originals.items():
            target.write_bytes(data)
    check_archive_scope(root)
    print(f'PASS: valid manifest and {cases} refusal cases; all source bytes restored')


if __name__ == '__main__':
    main()
