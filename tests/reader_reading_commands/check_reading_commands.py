def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def run(command, log, timeout=900):
    result = subprocess.run(command, capture_output=True, text=True, encoding='utf-8', errors='replace', timeout=timeout)
    Path(log).write_text(f'$ {" ".join(map(str, command))}\nexit={result.returncode}\n--- stdout\n{result.stdout}\n--- stderr\n{result.stderr}', encoding='utf-8')
    return result


def sqlite_providers(map_text):
    providers = set(re.findall(r'([A-Za-z0-9_.\-]+\.a)\(sqlite3\.c\.o\)', map_text))
    providers |= {name + '.lib' for name in re.findall(r'([A-Za-z0-9_.\-]+?)(?:\.lib)?:sqlite3\.c\.obj', map_text)}
    return sorted(providers)


def race_round(probe, out, index, problems):
    folder = out / f'race-{index}'
    folder.mkdir()
    db, params, barrier = folder / 'race.sqlite', folder / 'params.json', folder / 'go'
    setup = run([probe, '--mode', 'setup', '--db', str(db), '--params', str(params)], folder / 'setup.log')
    if setup.returncode != 0:
        problems.append(f'race {index}: setup exit {setup.returncode}')
        return {'round': index, 'setup_failed': True}
    revs = [secrets.token_hex(16), secrets.token_hex(16)]
    processes = []
    for n, rev in enumerate(revs):
        result = folder / f'racer-{n}.json'
        processes.append((rev, result, subprocess.Popen(
            [probe, '--mode', 'race', '--db', str(db), '--params', str(params), '--barrier', str(barrier), '--rev', rev, '--out', str(result)],
            stdout=subprocess.PIPE, stderr=subprocess.PIPE)))
    time.sleep(1.5)
    barrier.write_text('go')
    codes = [p.wait(timeout=300) for _, _, p in processes]
    results = [json.loads(r.read_text(encoding='utf-8')) if r.exists() else None for _, r, _ in processes]
    verify = run([probe, '--mode', 'verify', '--db', str(db), '--params', str(params), '--revs', ','.join(revs), '--out', str(folder / 'verify.json')], folder / 'verify.log')
    state = json.loads((folder / 'verify.json').read_text(encoding='utf-8')) if (folder / 'verify.json').exists() else {}
    if any(codes) or verify.returncode != 0 or any(r is None for r in results):
        problems.append(f'race {index}: process failure {codes} verify={verify.returncode}')
        return {'round': index, 'codes': codes, 'results': results, 'state': state}
    winners = [r for r in results if r['status'] == 'OK' and r['created'] == 1]
    losers = [r for r in results if r not in winners]
    if len(winners) != 1 or len(losers) != 1 or losers[0]['status'] == 'OK' or losers[0]['created'] != 0:
        problems.append(f'race {index}: expected exactly one winner, got {results}')
    elif not (state.get('heads') == [winners[0]['rev']] and state.get('retained_racers') == 1 and state.get('revisions') == 2
              and state.get('outbox_rows_for_entity') == 2 and state.get('safe') is True and state.get('deleted') is True):
        problems.append(f'race {index}: history or outbox split: {state}')
    return {'round': index, 'results': results, 'state': state}


def main():
    parser = argparse.ArgumentParser()
    for name in ('probe', 'c-consumer', 'fixtures', 'font', 'output', 'link-map'):
        parser.add_argument('--' + name, required=True)
    parser.add_argument('--race-rounds', type=int, default=6)
    args = parser.parse_args()
    out = Path(args.output)
    work = out / 'work'
    work.mkdir(parents=True, exist_ok=False)
    problems = []

    def need(ok, message):
        if not ok:
            problems.append(message)

    c_run = run([args.c_consumer, str(out / 'c-consumer.sqlite')], out / 'c-consumer.log')
    need(c_run.returncode == 0, f'C consumer exit {c_run.returncode}')

    manifest = json.loads((Path(args.fixtures) / 'manifest.json').read_text(encoding='utf-8'))
    command = [args.probe, '--fixtures', args.fixtures, '--font', args.font, '--work', str(work), '--report', str(out / 'report.json')]
    for role, item in sorted(manifest.items()):
        command += ['--sha', f'{role}={item["sha256"]}']
    probe = run(command, out / 'probe.log')
    need(probe.returncode == 0, f'probe exit {probe.returncode}')
    for name, result in (('c-consumer', c_run), ('probe', probe)):
        print(f'--- {name} exit={result.returncode}\n{result.stdout[-3000:]}\n{result.stderr[-3000:]}'.encode('ascii', 'backslashreplace').decode('ascii'))
    report_path = out / 'report.json'
    if not report_path.exists():
        problems.append('probe wrote no report')
        report = {'cases': [], 'checks': []}
    else:
        report = json.loads(report_path.read_text(encoding='utf-8'))

    checks = report.get('checks', [])
    failed = [c['name'] for c in checks if not c['pass']]
    need(not failed, f'probe checks failed: {failed}')
    names = [c['name'] for c in checks]
    cases = {c['label']: c for c in report.get('cases', [])}
    for label, kind in LABELS.items():
        case = cases.get(label)
        if case is None:
            problems.append(f'missing case {label}')
            continue
        need(case.get('passed') is True and case.get('kind') == kind, f'case {label} did not pass as {kind}')
        steps = PROGRESS_STEPS if kind == 'progress' else ANNOTATION_STEPS
        for step in steps:
            wanted = f'{label} {step}'
            need(any(n == wanted for n in names), f'missing check: {wanted}')
    need(set(cases) == set(LABELS), f'unexpected cases: {sorted(set(cases) ^ set(LABELS))}')
    modes = {label: cases[label].get('mode') for label in cases}
    need({'reflow_global', 'epub_chapter', 'fixed_page'} <= set(modes.values()), f'modes covered: {sorted(set(modes.values()))}')
    for label in ('txt-bookmark', 'epub-bookmark', 'pdf-bookmark', 'txt-progress', 'epub-progress-unique-part', 'cbz-progress-textless-page'):
        need(cases.get(label, {}).get('version') == 2, f'{label} is not anchor v2')
    for required in REQUIRED_CHECKS:
        matching = [c for c in checks if c['name'].startswith(required)]
        need(bool(matching) and all(c['pass'] for c in matching), f'required check missing or failed: {required}')
    for role in ('txt', 'epub', 'pdf', 'cbz'):
        need(report.get('books', {}).get(role, {}).get('book_key', '').endswith(':' + manifest[role]['sha256']), f'{role}: key is not the generated original SHA-256')
    need(report.get('failures') == 0, f'probe failures {report.get("failures")}')

    races = [race_round(args.probe, out, i, problems) for i in range(args.race_rounds)]

    map_text = Path(args.link_map).read_text(encoding='utf-8', errors='replace') if Path(args.link_map).exists() else ''
    providers = sqlite_providers(map_text)
    need(len(providers) == 1, f'expected exactly one vendored SQLite archive in the link map, got {providers}')
    need('libsqlite3.so' not in map_text and 'libsqlite3.dylib' not in map_text and 'winsqlite3' not in map_text, 'system SQLite must not satisfy native providers')

    summary = {
        'identity': {key: os.environ.get(key) for key in ('GITHUB_SHA', 'GITHUB_RUN_ID', 'GITHUB_RUN_ATTEMPT', 'GITHUB_JOB', 'RUNNER_OS', 'GITHUB_REF_NAME')},
        'originals': manifest, 'probe_sha256': sha(args.probe), 'c_consumer_sha256': sha(args.c_consumer),
        'report_sha256': sha(report_path) if report_path.exists() else None,
        'sdk_version': report.get('sdk_version'), 'parser_version': report.get('parser_version'),
        'module_versions': {k: report.get(k) for k in ('revisions_version', 'reading_state_version', 'commands_version')},
        'sqlite': {'version': report.get('sqlite_version'), 'source_id': report.get('sqlite_source_id'), 'link_providers': providers},
        'cases': report.get('cases', []), 'checks_total': len(checks), 'checks_failed': len(failed), 'races': races,
        'problems': problems,
        'reading_commands_accepted': not problems,
        'host_integration_accepted': False,
        'uncovered': UNCOVERED,
    }
    (out / 'summary.json').write_text(json.dumps(summary, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(json.dumps({k: v for k, v in summary.items() if k not in ('cases', 'races')}, ensure_ascii=True, indent=1))
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
