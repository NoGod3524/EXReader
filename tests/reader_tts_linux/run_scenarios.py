#!/usr/bin/env python3
"""J19 Linux reader TTS scenario driver.

Runs on a GitHub Actions Ubuntu runner only. It owns the real Speech Dispatcher
lifecycle (start, kill, restart), executes the installed-package consumers and
the fault-injection suite, then merges their named results and validates them
against the expectations fixed in expected_cases.json before looking at any
outcome. Any failing, missing, duplicated or unexpected case fails the run.
"""
import argparse
import hashlib
import json
import os
import shutil
import signal
import socket
import subprocess
import sys
import time

SPD_PREFIX = "speech-dispat"


def log(msg):
    print(msg, flush=True)


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def daemon_pids():
    pids = []
    for entry in os.listdir("/proc"):
        if not entry.isdigit():
            continue
        try:
            with open("/proc/%s/comm" % entry, "r") as f:
                comm = f.read().strip()
        except OSError:
            continue
        if comm.startswith(SPD_PREFIX):
            pids.append(int(entry))
    return pids


def kill_daemons(timeout=15.0):
    for pid in daemon_pids():
        try:
            os.kill(pid, signal.SIGKILL)
        except OSError:
            pass
    deadline = time.time() + timeout
    while time.time() < deadline:
        if not daemon_pids():
            return True
        time.sleep(0.1)
    return not daemon_pids()


def socket_probe(path):
    s = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
    s.settimeout(2.0)
    try:
        s.connect(path)
        return True
    except OSError:
        return False
    finally:
        s.close()


def discover_socket(candidates):
    for path in candidates:
        if path and os.path.exists(path) and socket_probe(path):
            return path
    return None


def socket_candidates():
    out = []
    xdg = os.environ.get("XDG_RUNTIME_DIR")
    home = os.path.expanduser("~")
    if xdg:
        out.append(os.path.join(xdg, "speech-dispatcher", "speechd.sock"))
    out.append(os.path.join("/run/user/%d" % os.getuid(), "speech-dispatcher", "speechd.sock"))
    out.append(os.path.join(home, ".cache", "speech-dispatcher", "speechd.sock"))
    out.append(os.path.join(home, ".speech-dispatcher", "speechd.sock"))
    out.append("/tmp/speech-dispatcher/speechd.sock")
    return out


def sockets_from_log(text):
    found = []
    for line in (text or "").splitlines():
        if "socket" in line.lower():
            for token in line.replace(",", " ").split():
                if token.endswith("speechd.sock"):
                    found.append(token)
    return found


def run(cmd, log_path, timeout=900, env=None):
    started = time.time()
    try:
        proc = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                              timeout=timeout, env=env)
        out = proc.stdout.decode("utf-8", "replace")
        rc = proc.returncode
    except subprocess.TimeoutExpired as exc:
        out = (exc.stdout or b"").decode("utf-8", "replace") + "\n[timeout after %ss]" % timeout
        rc = -9
    except OSError as exc:
        out = "[could not execute %r: %s]" % (cmd, exc)
        rc = -1
    with open(log_path, "w") as f:
        f.write("$ %s\n" % " ".join(cmd))
        f.write(out)
        f.write("\n[exit %d, %.1fs]\n" % (rc, time.time() - started))
    log("$ %s -> exit %d" % (" ".join(cmd), rc))
    return rc, out


START_SCRIPT_TEMPLATE = """#!/bin/sh
# Generated by run_scenarios.py: start the system daemon and wait until its Unix
# socket accepts a connection. Used by the kill/restart scenario.
setsid __LAUNCH__ >>"__LOG__" 2>&1 &
i=0
while [ $i -lt 300 ]; do
  for s in "$XDG_RUNTIME_DIR/speech-dispatcher/speechd.sock" \
           "$HOME/.cache/speech-dispatcher/speechd.sock" \
           "$HOME/.speech-dispatcher/speechd.sock" \
           "/run/user/$(id -u)/speech-dispatcher/speechd.sock"; do
    if [ -S "$s" ] && python3 -c 'import socket,sys
s = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
s.settimeout(2.0)
try:
    s.connect(sys.argv[1])
except OSError:
    sys.exit(1)
sys.exit(0)' "$s"; then
      exit 0
    fi
  done
  i=$((i+1))
  sleep 0.1
done
exit 1
"""


def write_start_script(path, launch, log_path):
    body = START_SCRIPT_TEMPLATE.replace("__LAUNCH__", launch).replace("__LOG__", log_path)
    with open(path, "w") as f:
        f.write(body)
    os.chmod(path, 0o755)


def collect_env(runner_label, source_sha, binaries):
    env = {
        "source_sha": source_sha,
        "run_id": int(os.environ.get("GITHUB_RUN_ID", "0") or 0),
        "run_attempt": int(os.environ.get("GITHUB_RUN_ATTEMPT", "0") or 0),
        "job": os.environ.get("GITHUB_JOB", ""),
        "workflow": os.environ.get("GITHUB_WORKFLOW", ""),
        "runner_label": runner_label,
        "runner_os": os.environ.get("RUNNER_OS", ""),
        "image": "",
        "kernel": "",
        "compiler": "",
        "cmake": "",
        "speech_dispatcher": "",
        "espeak": "",
        "libspeechd_header_sha256": "",
        "binaries": binaries,
    }
    try:
        with open("/etc/os-release") as f:
            for line in f:
                if line.startswith("PRETTY_NAME="):
                    env["image"] = line.split("=", 1)[1].strip().strip('"')
    except OSError:
        pass
    for key, cmd in (("kernel", ["uname", "-r"]),
                     ("cmake", ["cmake", "--version"]),
                     ("speech_dispatcher", ["speech-dispatcher", "--version"]),
                     ("espeak", ["espeak-ng", "--version"]),
                     ("compiler", ["cc", "--version"])):
        try:
            out = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                 timeout=60).stdout.decode("utf-8", "replace")
        except (OSError, subprocess.SubprocessError):
            out = ""
        env[key] = out.splitlines()[0].strip() if out.strip() else ""
    header = "/usr/include/speech-dispatcher/libspeechd.h"
    if os.path.exists(header):
        env["libspeechd_header_sha256"] = sha256_file(header)
    return env


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--build-dir", required=True)
    ap.add_argument("--output-dir", required=True)
    ap.add_argument("--expected", required=True)
    ap.add_argument("--source-sha", required=True)
    ap.add_argument("--runner-label", default="")
    ap.add_argument("--start-cmd", default="speech-dispatcher")
    args = ap.parse_args()

    out_dir = os.path.abspath(args.output_dir)
    logs = os.path.join(out_dir, "logs")
    os.makedirs(logs, exist_ok=True)
    build = os.path.abspath(args.build_dir)
    consumer = os.path.join(build, "reader-tts-consumer")
    consumer_cpp = os.path.join(build, "reader-tts-consumer-cpp")
    hook_suite = os.path.join(build, "tts-hook-suite")
    for path in (consumer, consumer_cpp, hook_suite):
        if not os.path.exists(path):
            log("missing test binary: %s" % path)
            return 3

    with open(args.expected) as f:
        expected = json.load(f)["phases"]

    daemon_log = os.path.join(logs, "speech-dispatcher.log")
    start_script = os.path.join(out_dir, "start-spd.sh")
    write_start_script(start_script, args.start_cmd, daemon_log)

    env_note = {
        "xdg_runtime_dir": os.environ.get("XDG_RUNTIME_DIR", ""),
        "start_cmd": args.start_cmd,
    }

    kill_daemons()
    rc, _ = run(["/bin/sh", start_script], os.path.join(logs, "daemon-start-1.log"), timeout=180)
    pids = daemon_pids()
    log_text = ""
    if os.path.exists(daemon_log):
        with open(daemon_log, "r", errors="replace") as f:
            log_text = f.read()
    sock = discover_socket(socket_candidates() + sockets_from_log(log_text))
    env_note["daemon_pids"] = pids
    env_note["socket"] = sock or ""
    log("daemon pids=%s socket=%s" % (pids, sock))
    if rc != 0 or not pids or not sock:
        detail = "daemon unavailable: rc=%d pids=%s socket=%s" % (rc, pids, sock)
        env_note["preflight"] = detail
        payload = {
            "schema": 1,
            "package": "J19-reader-tts-linux",
            "source_sha": args.source_sha,
            "env": env_note,
            "counts": {"pass": 0, "fail": 1, "skip": 0, "other": 0},
            "cases": [{"name": "environment_daemon_preflight", "phase": "startup",
                       "status": "fail", "detail": detail}],
            "problems": [detail],
            "accepted": False,
        }
        with open(os.path.join(out_dir, "results.json"), "w") as f:
            json.dump(payload, f, indent=2)
        log(detail)
        return 2

    # libspeechd derives the same socket from XDG_RUNTIME_DIR as the daemon, so
    # the default address is used. An explicit SPEECHD_ADDRESS was rejected by
    # 0.11.1 ("Unknown or unsupported communication method") and disabled every
    # connection, so it is never set here.
    test_env = dict(os.environ)
    test_env.pop("SPEECHD_ADDRESS", None)

    # libspeechd may resolve its default socket either from XDG_RUNTIME_DIR or
    # from the per-user cache directory; keep both candidate defaults valid so a
    # version difference cannot silently disable the connection.
    fallback = os.path.join(os.path.expanduser("~"), ".cache", "speech-dispatcher",
                            "speechd.sock")
    if sock and not os.path.exists(fallback):
        try:
            os.makedirs(os.path.dirname(fallback), exist_ok=True)
            os.symlink(sock, fallback)
            env_note["fallback_socket_symlink"] = "%s -> %s" % (fallback, sock)
        except OSError as exc:
            env_note["fallback_socket_symlink"] = "not created: %s" % exc

    spd_say = shutil.which("spd-say")
    env_note["preflight_spd_say_exit"] = None
    if spd_say:
        rc_say, out_say = run([spd_say, "-w", "-l", "en", "preflight"],
                              os.path.join(logs, "preflight-spd-say.log"), timeout=180,
                              env=test_env)
        env_note["preflight_spd_say_exit"] = rc_say
        env_note["preflight_spd_say_output"] = out_say.strip()[:400]
        if "Failed to connect" in out_say:
            # Keep the exact truth about the address syntax in the evidence.
            probes = {}
            for label, value in (("unix_socket_equals", "unix_socket=%s" % sock),
                                 ("unix_socket_colon", "unix_socket:%s" % sock),
                                 ("raw_path", sock)):
                probe_env = dict(test_env)
                probe_env["SPEECHD_ADDRESS"] = value
                rc_p, out_p = run([spd_say, "probe"],
                                  os.path.join(logs, "address-probe-%s.log" % label),
                                  timeout=60, env=probe_env)
                probes[label] = {"exit": rc_p, "output": out_p.strip()[:200]}
            env_note["speechd_address_probes"] = probes
            detail = "the system client cannot reach the daemon at %s: %s" % (
                sock, out_say.strip()[:200])
            env_note["preflight"] = detail
            payload = {
                "schema": 1,
                "package": "J19-reader-tts-linux",
                "source_sha": args.source_sha,
                "env": env_note,
                "counts": {"pass": 0, "fail": 1, "skip": 0, "other": 0},
                "cases": [{"name": "environment_daemon_connection", "phase": "startup",
                           "status": "fail", "detail": detail}],
                "problems": [detail],
                "accepted": False,
            }
            with open(os.path.join(out_dir, "results.json"), "w") as f:
                json.dump(payload, f, indent=2)
            log(detail)
            return 2

    phase_files = []

    def run_phase(name, cmd, timeout=1800):
        out_file = os.path.join(out_dir, "%s.json" % name)
        rc, _ = run(cmd + ["--output", out_file], os.path.join(logs, "%s.log" % name),
                    timeout=timeout, env=test_env)
        phase_files.append((name, out_file, rc))
        return rc

    run_phase("live", [consumer, "--phase", "live"], timeout=900)
    run_phase("cpp", [consumer_cpp, "--phase", "cpp"], timeout=300)
    run_phase("hook", [hook_suite, "--phase", "hook"], timeout=600)

    pids = daemon_pids()
    pid = pids[0] if pids else 0
    run_phase("kill", [consumer, "--phase", "kill", "--spd-pid", str(pid),
                       "--restart-cmd", start_script], timeout=240)
    env_note["killed_pid"] = pid
    env_note["daemon_pids_after_kill_phase"] = daemon_pids()

    kill_daemons()
    run_phase("down", [consumer, "--phase", "down"], timeout=180)
    env_note["daemon_pids_after_down_phase"] = daemon_pids()

    rc, _ = run(["/bin/sh", start_script], os.path.join(logs, "daemon-start-2.log"), timeout=180)
    env_note["restart_exit"] = rc
    env_note["daemon_pids_after_restart"] = daemon_pids()
    run_phase("recover", [consumer, "--phase", "recover"], timeout=240)

    cases = []
    per_phase = {}
    for name, path, rc in phase_files:
        if not os.path.exists(path):
            per_phase[name] = {"exit": rc, "cases": 0, "error": "missing result file"}
            continue
        try:
            with open(path) as f:
                data = json.load(f)
        except (OSError, ValueError) as exc:
            per_phase[name] = {"exit": rc, "cases": 0, "error": "unreadable: %s" % exc}
            continue
        phase_cases = data.get("cases") or []
        per_phase[name] = {"exit": rc, "cases": len(phase_cases), "failures": data.get("failures")}
        for case in phase_cases:
            merged = dict(case)
            merged["phase"] = name
            cases.append(merged)

    problems = []
    counts = {"pass": 0, "fail": 0, "skip": 0, "other": 0}
    for name, names in expected.items():
        got = [c["name"] for c in cases if c.get("phase") == name]
        for want in names:
            if got.count(want) == 0:
                problems.append("missing case %s/%s" % (name, want))
            elif got.count(want) > 1:
                problems.append("duplicate case %s/%s (%d)" % (name, want, got.count(want)))
        for have in got:
            if have not in names:
                problems.append("unexpected case %s/%s" % (name, have))
    for case in cases:
        status = case.get("status")
        label = "%s/%s" % (case.get("phase"), case.get("name"))
        if status == "pass":
            counts["pass"] += 1
        elif status == "fail":
            counts["fail"] += 1
            problems.append("failing case %s: %s" % (label, case.get("detail", "")))
        elif status == "skip":
            counts["skip"] += 1
            problems.append("skipped case %s: %s" % (label, case.get("detail", "")))
        else:
            counts["other"] += 1
            problems.append("unknown status %r for %s" % (status, label))
        if not case.get("detail"):
            problems.append("case %s has no detail" % label)

    binaries = {}
    for path in (consumer, consumer_cpp, hook_suite):
        if os.path.exists(path):
            binaries[os.path.basename(path)] = {
                "sha256": sha256_file(path),
                "bytes": os.path.getsize(path),
            }
    env_block = collect_env(args.runner_label, args.source_sha, binaries)
    env_block.update(env_note)
    env_block["phases"] = per_phase
    env_block["limits"] = {
        "max_utf8_bytes": 16384,
        "event_capacity": 128,
        "max_voices": 4096,
        "max_voice_field": 256,
        "id_memory": 256,
    }

    results = {
        "schema": 1,
        "package": "J19-reader-tts-linux",
        "source_sha": args.source_sha,
        "run_id": env_block["run_id"],
        "run_attempt": env_block["run_attempt"],
        "env": env_block,
        "counts": counts,
        "expected_cases": sum(len(v) for v in expected.values()),
        "cases": cases,
        "problems": problems,
        "accepted": not problems,
    }
    with open(os.path.join(out_dir, "results.json"), "w") as f:
        json.dump(results, f, indent=2)

    markdown = ["# J19 reader-tts-linux evidence", ""]
    markdown.append("- source: %s" % args.source_sha)
    markdown.append("- run/attempt: %s/%s on %s" % (env_block["run_id"], env_block["run_attempt"],
                                                    env_block["image"]))
    markdown.append("- Speech Dispatcher: %s" % env_block.get("speech_dispatcher", ""))
    markdown.append("- socket: %s" % env_block.get("socket", ""))
    markdown.append("- cases: %s" % json.dumps(counts))
    markdown.append("")
    if problems:
        markdown.append("## Problems")
        markdown.append("")
        for problem in problems:
            markdown.append("- %s" % problem)
    else:
        markdown.append("All expected cases passed.")
    markdown.append("")
    markdown.append("## Per phase")
    markdown.append("")
    for name, info in per_phase.items():
        markdown.append("- %s: %s" % (name, json.dumps(info)))
    with open(os.path.join(out_dir, "summary.md"), "w") as f:
        f.write("\n".join(markdown) + "\n")

    with open(os.path.join(out_dir, "files.sha256"), "w") as f:
        for base, dirs, names in os.walk(out_dir):
            dirs.sort()
            for name in sorted(names):
                path = os.path.join(base, name)
                rel = os.path.relpath(path, out_dir)
                if rel == "files.sha256":
                    continue
                f.write("%s  %s\n" % (sha256_file(path), rel))

    log("cases: %s" % json.dumps(counts))
    if problems:
        for problem in problems:
            log("PROBLEM %s" % problem)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
