def utf16_payload(value):
    if isinstance(value, list):
        return struct.pack("<%dH" % len(value), *value)
    return value.encode("utf-16-le")


def units_of(value):
    if isinstance(value, list):
        return len(value)
    return len(value.encode("utf-16-le")) // 2


def utf16_expected(value, capacity=CAPACITY):
    """Predict reader_command_utf16 per its documented contract."""
    if isinstance(value, list):
        i = 0
        while i < len(value):
            unit = value[i]
            if unit == 0:
                return (1, 0, b"")
            if 0xD800 <= unit <= 0xDBFF:
                if i + 1 >= len(value) or not (0xDC00 <= value[i + 1] <= 0xDFFF):
                    return (1, 0, b"")
                i += 2
                continue
            if 0xDC00 <= unit <= 0xDFFF:
                return (1, 0, b"")
            i += 1
        raise SystemExit("frozen code-unit list is unexpectedly convertible")
    encoded = value.encode("utf-8")
    if units_of(value) > 16384 or len(encoded) > 16384 or len(encoded) >= capacity:
        return (1, 0, b"")
    return (0, len(encoded), encoded)


def text_valid(encoded):
    """Predict the product valid_text predicate (strict UTF-8 + scalar bound)."""
    if len(encoded) > TEXT_MAX_BYTES:
        return False
    try:
        decoded = encoded.decode("utf-8")
    except UnicodeDecodeError:
        return False
    return len(decoded) <= TEXT_MAX_SCALARS


