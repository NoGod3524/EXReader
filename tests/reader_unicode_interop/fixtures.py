class Model(object):
    def __init__(self):
        self.books = {}
        self.shelves = {}
        self.tags = {}
        self.series = {}
        self.joins = {}
        self.revs = []
        self.by_label = {}
        self.heads = {}
        self.counts = {}

    def groups(self, kind):
        return {"shelf": self.shelves, "tag": self.tags, "series": self.series}[kind]

    def add(self, label, kind, key, op, parents, wire_bytes, book_key, source_bytes):
        item = dict(label=label, id=REVID[label], kind=kind, key=key, op=op,
                    parents=list(parents), wire=wire_bytes,
                    sha=sha256_hex(wire_bytes), book_key=book_key,
                    source_bytes=source_bytes)
        self.revs.append(item)
        self.by_label[label] = item
        self.heads[(kind, key)] = [REVID[label]]
        self.counts[(kind, key)] = self.counts.get((kind, key), 0) + 1
        AUX["rev." + label] = REVID[label]
        AUX["sha." + label] = item["sha"]
        AUX["entity_kind." + label] = kind
        AUX["key." + label] = key
        return item


