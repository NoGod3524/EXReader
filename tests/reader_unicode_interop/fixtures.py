"""Frozen G14 Unicode request container and independent expectations.

This file is the single source of truth for the cross-platform Unicode
consumer probe. It writes:

  cases.bin      binary request consumed by the installed consumers
  expected.json  per-observation expected values plus reopen/mirror aliases
  meta.json      fixture identity and counts

Everything here is derived from the frozen inputs with the documented public
contract (product schema 1, revision wire v1, catalog.h page/query rules).
No product code is executed or imported, so an expectation can never be
"generated by the implementation under test".

Contract facts encoded below (read from the handoff-listed sources):
  * book_key = format ":" sha256 ; library text <= 16384 bytes and <= 4096
    scalars, strict UTF-8 (rejects overlong forms, surrogates, > U+10FFFF)
  * group names <= 1024 bytes and <= 256 scalars, never empty
  * catalog ordering is (sort_title, book_key) ascending byte order, i.e.
    SQLite BINARY collation on the exact stored UTF-8 bytes
  * search is instr(lower(field), lower(query)) > 0 where lower() folds only
    ASCII A-Z, so Unicode bytes stay exact and no case/Unicode folding exists
  * the host supplies sort_title; the product never normalizes a stored text
  * reader_command_utf16: <= 16384 UTF-16 units, strict UTF-8, no NUL, no
    unpaired surrogate, at most 16384 output bytes plus terminator
  * revision wire v1 envelope is retained verbatim, escape sequences included
"""
