def write_container(path, items, aux, operations):
    blob = bytearray(MAGIC)
    blob += struct.pack("<I", VERSION)
    blob += struct.pack("<I", len(items))
    for name, kind, payload in items:
        raw = name.encode("ascii")
        blob += struct.pack("<I", len(raw)) + raw
        blob += struct.pack("<B", kind)
        blob += struct.pack("<I", len(payload)) + payload
    keys = sorted(key for key in aux if aux[key] is not None)
    blob += struct.pack("<I", len(keys))
    for key in keys:
        value = aux[key]
        kb = key.encode("ascii")
        vb = value.encode("ascii")
        blob += struct.pack("<I", len(kb)) + kb + struct.pack("<I", len(vb)) + vb
    blob += struct.pack("<I", len(operations))
    for name in operations:
        raw = name.encode("ascii")
        blob += struct.pack("<I", len(raw)) + raw
    with open(path, "wb") as handle:
        handle.write(bytes(blob))
    return len(blob)


