# --------------------------------------------------------------------------
# revision wire v1 reconstruction (documented envelope only)
# --------------------------------------------------------------------------
def jstr(data):
    out = bytearray(b'"')
    for ch in data:
        if ch == 0x22 or ch == 0x5C:
            out.append(0x5C)
            out.append(ch)
        elif ch < 32:
            out += ("\\u00%02x" % ch).encode("ascii")
        else:
            out.append(ch)
    return bytes(out) + b'"'


def wire(rid, kind, key, op, parents, payload):
    head = (b'{"version":1,"id":' + jstr(rid.encode("utf-8"))
            + b',"entity_kind":' + jstr(kind.encode("utf-8"))
            + b',"entity_key":' + jstr(key.encode("utf-8"))
            + b',"operation":' + jstr(op.encode("utf-8"))
            + b',"location_kind":"none","parents":[')
    body = b",".join(jstr(p.encode("utf-8")) for p in parents)
    return head + body + b'],"payload":' + payload + b"}"

def book_payload(fmt, sha, nbytes, title, author, favorite):
    return (b'{"format":' + jstr(fmt.encode("utf-8"))
            + b',"source_sha256":' + jstr(sha.encode("utf-8"))
            + b',"source_bytes":' + str(nbytes).encode("ascii")
            + b',"title":' + jstr(title)
            + b',"author":' + jstr(author)
            + b',"favorite":' + (b"true" if favorite else b"false") + b"}")


def group_payload(kind, name, parent, ordinal):
    out = b'{"name":' + jstr(name)
    if kind == "shelf":
        out += b',"parent_id":' + (b"null" if not parent else jstr(parent.encode("utf-8")))
        out += b',"ordinal":' + str(ordinal).encode("ascii")
    return out + b"}"


def member_payload(book_key, kind, group_id, ordinal):
    return (b'{"book_key":' + jstr(book_key.encode("utf-8"))
            + b',"collection_kind":' + jstr(kind.encode("utf-8"))
            + b',"collection_id":' + jstr(group_id.encode("utf-8"))
            + b',"ordinal":' + str(ordinal).encode("ascii") + b"}")


