def slice_rows(rows, cursor, direction, limit, inclusive=False):
    if cursor is None:
        selected = rows if direction > 0 else list(reversed(rows))
        return selected[:limit]
    out = []
    for row in (rows if direction > 0 else list(reversed(rows))):
        key = (row["sort"], row["key"])
        if direction > 0:
            ok = key >= cursor if inclusive else key > cursor
        else:
            ok = key < cursor
        if ok:
            out.append(row)
        if len(out) >= limit:
            break
    return out


