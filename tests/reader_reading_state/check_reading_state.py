"""Run the installed reading-state consumers and judge their real SDK report.

Actions only. Every original is generated by make_fixtures.py in the same job;
no capture, selector or fixture is synthesized here.
"""
import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
from pathlib import Path

REV_FORMAT = 4  # READER_REV_FORMAT
EXR_ARGUMENT = 1
UNCOVERED = [
    'progress sync through product revisions: every SDK progress selector is a point (empty exact); wire v1 refuses it',
    'bookmark sync: SDK bookmarks are points; wire v1 annotation selectors require nonempty exact',
    'text-free fixed pages (CBZ, empty PDF pages): only a point exists; wire v1 refuses it',
    'reflow selectors carrying an SDK chapter scope (EPUB in global storage): wire v1 reflow_global has no chapter field',
    'bounded EPUB bookmarks have no SDK point-note API; product revision would be the only store even after a wire change',
    'durable global annotation -> receiver SDK note map: schema1 has no table; an edit that crosses an interrupted SDK step and restart leaves a stale note',
    'EPUB parts whose path repeats in the spine: wire v1 carries only part_path, so the receiver refuses routing',
    'macOS, iOS and Android builds; host UI; WebDAV transport; six-platform interop',
]


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def run(command, log):
    result = subprocess.run(command, capture_output=True, text=True, encoding='utf-8', errors='replace')
    Path(log).write_text(f'$ {" ".join(map(str, command))}\nexit={result.returncode}\n--- stdout\n{result.stdout}\n--- stderr\n{result.stderr}', encoding='utf-8')
    return result


def sqlite_providers(map_text):
    providers = set()
    for line in map_text.splitlines():
        if 'sqlite3.c' not in line:
            continue
        for match in re.finditer(r'([A-Za-z0-9_.\-]*sqlite[A-Za-z0-9_.\-]*\.(?:a|lib))', line):
            providers.add(match.group(1))
    return sorted(providers)


def main():
    parser = argparse.ArgumentParser()
    for name in ('probe', 'c-consumer', 'fixtures', 'font', 'output', 'link-map'):
        parser.add_argument('--' + name, required=True)
    args = parser.parse_args()
    out = Path(args.output)
    work = out / 'work'
    work.mkdir(parents=True, exist_ok=False)
    problems = []

    def need(ok, message):
        if not ok:
            problems.append(message)

    c_run = run([args.c_consumer], out / 'c-consumer.log')
    need(c_run.returncode == 0, f'C consumer exit {c_run.returncode}')

    manifest = json.loads((Path(args.fixtures) / 'manifest.json').read_text(encoding='utf-8'))
    command = [args.probe, '--fixtures', args.fixtures, '--font', args.font, '--work', str(work), '--report', str(out / 'report.json')]
    for role, item in sorted(manifest.items()):
        command += ['--sha', f'{role}={item["sha256"]}']
    probe = run(command, out / 'probe.log')
    need(probe.returncode == 0, f'probe exit {probe.returncode}')
    report_path = out / 'report.json'
    if not report_path.exists():
        problems.append('probe wrote no report')
        report = {'cases': [], 'lifecycle': [], 'checks': [], 'exchanged': []}
    else:
        report = json.loads(report_path.read_text(encoding='utf-8'))

    failed_checks = [c for c in report.get('checks', []) if not c['pass']]
    need(not failed_checks, f'probe checks failed: {[c["name"] for c in failed_checks]}')
    need(report.get('receiver_mislocated', 1) == 0, 'receiver FOUND at a different range')
    need(report.get('unresolved_writes', 1) == 0, 'SDK write without FOUND')
    for role in ('txt', 'epub', 'pdf', 'cbz'):
        ids = report.get('sdk_ids', {}).get(role, {})
        need(ids.get('A') is not None and ids.get('A') != ids.get('B'), f'{role}: SDK IDs must differ across libraries')
        book = report.get('books', {}).get(role, {})
        need(book.get('book_key', '').endswith(':' + manifest[role]['sha256']), f'{role}: global key is not the generated original SHA-256')

    cases = {c['id']: c for c in report.get('cases', [])}
    found_v1 = set()
    for cid, case in cases.items():
        capture = case.get('capture')
        adapter = case.get('adapter', {})
        literal = case.get('v1_literal', {})
        receiver = case.get('receiver', {})
        if capture is None:
            continue
        if capture['exact_bytes'] == 0:
            need(adapter.get('status') == 'NOT_REPRESENTABLE' and adapter.get('gap') in ('point', 'textless_page'),
                 f'{cid}: empty-exact capture must be NOT_REPRESENTABLE point/textless')
            need(literal.get('status') == REV_FORMAT, f'{cid}: literal v1 point must be refused as FORMAT')
        if adapter.get('status') == 'OK':
            need(literal.get('status') == 0, f'{cid}: adapter accepted bytes that literal v1 refuses')
        if 'v2_proposal' in case:
            need(case['v2_proposal'].get('v1_client_status') == REV_FORMAT, f'{cid}: unchanged v1 client must refuse anchor_version 2')
        if receiver:
            if receiver.get('state') == 'FOUND' and receiver.get('status') == 'OK':
                need(receiver['start'] == receiver['expected_start'] and receiver['end'] == receiver['expected_end'], f'{cid}: mislocated')
                if receiver.get('path') == 'v1' and receiver.get('sdk_persisted'):
                    found_v1.add(case.get('mode'))
            else:
                need(not receiver.get('sdk_persisted'), f'{cid}: SDK persisted without FOUND')

    def case_is(cid, **expected):
        case = cases.get(cid)
        if case is None:
            problems.append(f'missing case {cid}')
            return
        for path, value in expected.items():
            node = case
            for part in path.split('__'):
                node = node.get(part, {}) if isinstance(node, dict) else {}
            need(node == value, f'{cid}: {path} is {node!r}, expected {value!r}')

    case_is('txt-invalid-utf8-offset-refused', capture_status=EXR_ARGUMENT)
    case_is('txt-highlight-ambiguous', sender_resolve='AMBIGUOUS', receiver__state='AMBIGUOUS', receiver__sdk_persisted=False)
    case_is('txt-missing-cross-original', receiver__state='MISSING', receiver__sdk_persisted=False)
    case_is('pdf-highlight-ambiguous-repeated-lines', receiver__state='AMBIGUOUS', receiver__sdk_persisted=False)
    case_is('epub-highlight-repeated-spine-route', receiver__status='IDENTITY', receiver__sdk_persisted=False)
    case_is('pdf-textless-page-bookmark', adapter__gap='textless_page')
    case_is('cbz-textless-page-bookmark', adapter__gap='textless_page')
    for cid in ('txt-progress-point-multibyte', 'txt-progress-point-start', 'txt-progress-point-end', 'epub-progress-point', 'txt-bookmark-point', 'pdf-bookmark-point'):
        case_is(cid, adapter__status='NOT_REPRESENTABLE', adapter__gap='point')
    case_is('epub-global-chapter-scope', adapter__gap='chapter_scope')
    need(found_v1 >= {'reflow_global', 'epub_chapter', 'fixed_page'}, f'v1 FOUND+persisted modes: {sorted(found_v1)}')

    steps = {s['step']: s for s in report.get('lifecycle', [])}

    def step_is(name, **expected):
        s = steps.get(name)
        if s is None:
            problems.append(f'missing lifecycle step {name}')
            return
        for key, value in expected.items():
            need(s.get(key) == value, f'lifecycle {name}: {key} is {s.get(key)!r}, expected {value!r}')

    step_is('create-and-exact-retry', B_selection='SAFE', B_action='created', B_text='first note')
    step_is('edit', B_selection='SAFE', B_action='updated', B_text='edited note')
    step_is('concurrent-after-exchange', A_selection='CONCURRENT', B_selection='CONCURRENT', A_action='no-sdk-write', B_action='no-sdk-write',
            A_text='A concurrent', B_text='B concurrent')
    step_is('merge', B_selection='SAFE', B_text='merged note')
    step_is('tombstone', B_selection='SAFE', B_action='removed')
    step_is('put-after-delete-blocked', B_selection='BLOCKED_RESTORE', B_action='no-sdk-write')
    step_is('restore', B_selection='SAFE', B_action='created', B_text='restored note')
    step_is('offline-newest-first', B_selection='PENDING_PARENTS', B_action='no-sdk-write')
    step_is('offline-middle', B_selection='PENDING_PARENTS', B_action='no-sdk-write')
    step_is('offline-complete', B_selection='SAFE', B_text='offline three')
    step_is('restart-after-sdk-commit', B_action='adopted')
    step_is('restart-reconcile-again', B_action='adopted')
    gap = steps.get('durable-annotation-map-gap', {})
    progress_before = steps.get('receiver-progress-after-cases', {})

    exchanged = report.get('exchanged', [])
    need(len(exchanged) >= 10 and all(re.fullmatch('[0-9a-f]{64}', e['sha256']) for e in exchanged), 'revision exchange evidence is incomplete')

    map_text = Path(args.link_map).read_text(encoding='utf-8', errors='replace') if Path(args.link_map).exists() else ''
    providers = sqlite_providers(map_text)
    need(len(providers) == 1, f'expected exactly one vendored SQLite archive in the link map, got {providers}')
    need('libsqlite3.so' not in map_text and 'winsqlite3' not in map_text, 'system SQLite must not satisfy native providers')

    summary = {
        'identity': {key: os.environ.get(key) for key in ('GITHUB_SHA', 'GITHUB_RUN_ID', 'GITHUB_RUN_ATTEMPT', 'GITHUB_JOB', 'RUNNER_OS', 'GITHUB_REF_NAME')},
        'originals': manifest,
        'probe_sha256': sha(args.probe), 'c_consumer_sha256': sha(args.c_consumer),
        'report_sha256': sha(report_path) if report_path.exists() else None,
        'sdk_version': report.get('sdk_version'), 'parser_version': report.get('parser_version'),
        'sqlite': {'version': report.get('sqlite_version'), 'source_id': report.get('sqlite_source_id'), 'link_providers': providers},
        'sdk_ids': report.get('sdk_ids'),
        'cases': [{k: case.get(k) for k in ('id', 'book', 'kind', 'mode', 'sender_resolve')} |
                  {'gap': case.get('adapter', {}).get('gap'), 'adapter': case.get('adapter', {}).get('status'),
                   'v1_literal': case.get('v1_literal', {}).get('status'), 'receiver': case.get('receiver', {}).get('state'),
                   'receiver_path': case.get('receiver', {}).get('path'), 'persisted': case.get('receiver', {}).get('sdk_persisted')}
                  for case in report.get('cases', [])],
        'checks_total': len(report.get('checks', [])), 'checks_failed': len(failed_checks),
        'receiver_found': report.get('receiver_found'), 'receiver_mislocated': report.get('receiver_mislocated'),
        'unresolved_writes': report.get('unresolved_writes'),
        'revisions_exchanged': len(exchanged),
        'receiver_progress_untouched_by_remote_annotations': progress_before.get('start') == steps.get('receiver-progress-final', {}).get('start'),
        'durable_annotation_map_gap': gap,
        'problems': problems,
        'v1_highlight_roundtrip_accepted': not problems,
        'reading_state_sync_complete': False,
        'progress_bookmark_sync_accepted': False,
        'uncovered': UNCOVERED,
    }
    (out / 'summary.json').write_text(json.dumps(summary, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(json.dumps({'problems': problems, 'cases': len(cases), 'checks': summary['checks_total']}, ensure_ascii=False))
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
