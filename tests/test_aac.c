  CHECK(exr_aac_format(aac)->sample_rate==rate && exr_aac_format(aac)->channels==channels);
  baseline=malloc(frames*channels*sizeof(*baseline)); out=malloc((frames+1171)*channels*sizeof(*out)); CHECK(baseline && out);
  stop=1; OK(exr_aac_read(aac,0,frames,baseline,&got,NULL,&error)); CHECK(got==frames && exr_aac_format(aac)->frames==frames);
