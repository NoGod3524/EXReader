"""Run the installed jump-history consumers and judge their real report.

Actions only. Every original is generated by make_fixtures.py in the same job;
no capture, selector, wire or history entry is synthesized here.
"""
import argparse
import hashlib
import json
import os
import subprocess
import sys
from pathlib import Path

UNCOVERED = [
    'hosts: the four production hosts are not wired to this component; root owns the wiring and the shared-source revalidation',
    'ui: no desktop, GTK, Android or Apple jump/back/forward control, menu or shortcut is claimed here',
    'persistence: the stack is in memory only; no restart, cross-device or sync entity is claimed',
    'integration: no dependence on G03/G04 search, table-of-contents or annotation hosts is claimed',
    'progress: the component stores positions but writes no reading progress, no SDK note and no product revision by design',
    'performance: no latency or CPU budget is claimed for the stack; only the documented entry and byte caps are enforced',
    'scale: real captures cover four generated originals; no real user library, corpus or private cloud storage is used',
]

REQUIRED = [
    'a real TXT reflow capture is stored as ADDED',
    'the same landing again is UNCHANGED',
    'a page turn inside one book coalesces',
    'a real EPUB chapter capture is stored as ADDED',
    'a real PDF page capture is stored as ADDED',
    'a real CBZ textless page point is stored as ADDED',
    'peek does not move the cursor',
    'the host re-resolves the PDF target on its own SDK owner',
    'the host re-resolves the EPUB target on its own SDK owner',
    'the host re-resolves the TXT target on its own SDK owner',
    'complete moves the cursor after FOUND',
    'nothing is behind the oldest entry',
    'forward returns the entry that was left behind',
    'a cancelled jump leaves the cursor and generation alone',
    'complete refuses an item the history has moved past',
    'an ambiguous target is not reported as found',
    'an unresolved target does not move the cursor',
    'a repeated spine path is refused when only the path is known',
    'the stored spine index addresses the repeated part',
    'the repeated spine target re-resolves FOUND through its index',
    'a textless fixed page target resolves FOUND',
    'the entry cap keeps exactly four entries',
    'the entry cap dropped the two oldest',
    'a position above the byte budget is TOO_LARGE',
    'a wire above the per-entry cap is TOO_LARGE',
    'the byte budget is never exceeded',
    'the byte budget evicts the oldest entries',
    '257 entries is refused above the hard cap',
    'an unknown limits struct version is refused',
    'an annotation wire is not a reading position',
    'a delete wire is not a reading position',
    'a truncated position wire is refused',
    'an unknown anchor version is refused',
    'a foreign thread cannot peek',
    'adopt_thread hands ownership to the caller',
    'an item outlives the closed history',
    'a released-history item still decodes through the installed validator',
    'no product revision and no outbox row was created',
    'no SDK progress record was written',
    'no SDK note was written',
    'the library and product databases are byte-identical after the whole run',
    'the same measurement detects real product and SDK writes',
]
MOVE_STEPS = ['back-pdf', 'back-epub', 'back-txt-oldest', 'forward-epub', 'back-textless-pdf']
CASE_MODES = {'txt-page-first': 'reflow_global', 'epub-chapter-search': 'epub_chapter',
              'pdf-page-one': 'fixed_page', 'cbz-textless-point': 'fixed_page'}


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def run(command, log):
    result = subprocess.run(command, capture_output=True, text=True, encoding='utf-8', errors='replace')
    Path(log).write_text('$ ' + ' '.join(map(str, command)) + '\nexit=' + str(result.returncode)
                         + '\n--- stdout\n' + result.stdout + '\n--- stderr\n' + result.stderr, encoding='utf-8')
    return result


def main():
    parser = argparse.ArgumentParser()
    for name in ('probe', 'c-consumer', 'fixtures', 'font', 'installed', 'platform', 'output'):
        parser.add_argument('--' + name, required=True)
    args = parser.parse_args()
    out = Path(args.output)
    work = out / 'work'
    work.mkdir(parents=True, exist_ok=False)
    problems = []

    def need(ok, message):
        if not ok:
            problems.append(message)

    manifest = json.loads((Path(args.fixtures) / 'manifest.json').read_text(encoding='utf-8'))

    c_run = run([args.c_consumer, str(work)], out / 'c-consumer.log')
    need(c_run.returncode == 0, 'C consumer exit ' + str(c_run.returncode))

    command = [args.probe, '--fixtures', args.fixtures, '--font', args.font, '--work', str(work),
               '--report', str(out / 'report.json')]
    for role, item in sorted(manifest.items()):
        command += ['--sha', role + '=' + item['sha256']]
    probe = run(command, out / 'probe.log')
    need(probe.returncode == 0, 'probe exit ' + str(probe.returncode))
    for name, result in (('c-consumer', c_run), ('probe', probe)):
        text = '--- ' + name + ' exit=' + str(result.returncode) + '\n' + result.stdout[-4000:] + '\n' + result.stderr[-4000:]
        print(text.encode('ascii', 'backslashreplace').decode('ascii'))

    report_path = out / 'report.json'
    if not report_path.exists():
        problems.append('the probe wrote no report')
        report = {'cases': [], 'lifecycle': [], 'checks': [], 'no_write': {}}
    else:
        report = json.loads(report_path.read_text(encoding='utf-8'))

    checks = report.get('checks', [])
    by_name = {c['name']: c for c in checks}
    failed = [c['name'] for c in checks if not c['pass']]
    need(not failed, 'probe checks failed: ' + repr(failed))
    missing = [name for name in REQUIRED if name not in by_name]
    need(not missing, 'required named checks missing: ' + repr(missing))
    need(report.get('failures') == 0, 'probe reported failures ' + repr(report.get('failures')))
    need(len(checks) >= len(REQUIRED), 'only ' + str(len(checks)) + ' checks ran')

    cases = {c['id']: c for c in report.get('cases', [])}
    for cid, mode in CASE_MODES.items():
        case = cases.get(cid)
        if case is None:
            problems.append('missing stored-wire case ' + cid)
            continue
        need(case.get('mode') == mode, cid + ': mode is ' + repr(case.get('mode')) + ', expected ' + mode)
        need(int(case.get('stored_wire_bytes', 0)) > 0, cid + ': stored wire is empty')
        need(int(case.get('accounted_bytes', 0)) >= int(case.get('stored_wire_bytes', 0)), cid + ': accounting is short')
        need(case.get('operation') == 'put' and case.get('entity_kind') == 'progress',
             cid + ': stored wire is not a progress put')
        need(case.get('outcome') in ('ADDED', 'COALESCED'), cid + ': outcome is ' + repr(case.get('outcome')))
    for role in ('txt', 'epub', 'pdf', 'cbz'):
        case = next((c for c in cases.values() if c.get('book') == role), None)
        need(case is not None and case.get('book_key', '').endswith(':' + manifest[role]['sha256']),
             role + ': stored book_key is not the generated original SHA-256')
    need(cases.get('cbz-textless-point', {}).get('exact_bytes') == 0,
         'the textless point must store an empty quote')

    steps = {s['step']: s for s in report.get('lifecycle', [])}
    for step in MOVE_STEPS:
        entry = steps.get(step)
        if entry is None:
            problems.append('missing move ' + step)
            continue
        need(int(entry.get('count', 0)) >= 2, step + ': fewer than two entries during the move')
    back = steps.get('back-pdf', {})
    need(int(back.get('from_cursor', -1)) > int(back.get('to_cursor', -1)), 'back-pdf did not move the cursor back')
    forward = steps.get('forward-epub', {})
    need(int(forward.get('to_cursor', -1)) > int(forward.get('from_cursor', -1)), 'forward-epub did not move the cursor forward')
    need(int(report.get('moves', 0)) >= len(MOVE_STEPS), 'fewer moves than expected: ' + repr(report.get('moves')))

    no_write = report.get('no_write', {})
    need(no_write.get('revision_rows') == 0 and no_write.get('outbox_rows') == 0, 'product revision state is not empty')
    need(no_write.get('sdk_progress_records') == 0, 'an SDK progress record exists')
    need(no_write.get('sdk_notes') == 0 and no_write.get('sdk_fixed_notes') == 0 and no_write.get('sdk_epub_notes') == 0,
         'an SDK note exists')
    need(no_write.get('databases_unchanged') is True, 'the databases changed during the jump-history run')
    need(no_write.get('control_write_changed') is True, 'the write measurement is not sensitive')

    installed = Path(args.installed)
    header = installed / 'include' / 'reader_jump_history.h'
    need(header.exists(), 'the installed package has no reader_jump_history.h')
    libraries = sorted(p.relative_to(installed).as_posix() for p in installed.glob('lib/*'))
    library = next((name for name in libraries if 'jump_history' in name), None)
    need(library is not None, 'the installed package has no jump-history library')

    summary = {
        'identity': {key: os.environ.get(key) for key in
                     ('GITHUB_SHA', 'GITHUB_RUN_ID', 'GITHUB_RUN_ATTEMPT', 'GITHUB_JOB', 'RUNNER_OS', 'GITHUB_REF_NAME')},
        'platform': args.platform,
        'originals': manifest,
        'installed': {
            'header_sha256': sha(header) if header.exists() else None,
            'library_sha256': sha(installed / library) if library else None,
            'files': libraries,
        },
        'probe_sha256': sha(args.probe),
        'c_consumer_sha256': sha(args.c_consumer),
        'report_sha256': sha(report_path) if report_path.exists() else None,
        'sdk_version': report.get('sdk_version'),
        'parser_version': report.get('parser_version'),
        'jump_history_version': report.get('jump_history_version'),
        'reading_state_version': report.get('reading_state_version'),
        'revisions_version': report.get('revisions_version'),
        'books': report.get('books'),
        'cases': report.get('cases', []),
        'lifecycle': report.get('lifecycle', []),
        'cases_total': report.get('cases_total'),
        'checks_total': len(checks),
        'checks_failed': len(failed),
        'moves': report.get('moves'),
        'no_write': no_write,
        'problems': problems,
        'jump_history_module_accepted': not problems,
        'host_wiring_accepted': False,
        'uncovered': UNCOVERED,
    }
    (out / 'summary.json').write_text(json.dumps(summary, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(summary, ensure_ascii=True, indent=1))
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
