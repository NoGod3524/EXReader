#!/usr/bin/env python3
"""Generate the pinned Unicode 17 vertical-orientation table.

Python standard library only; normal builds use committed files, without network.
    python tools/generate_vertical.py --download
    python tools/generate_vertical.py --check
"""
# SPDX-License-Identifier: MIT
import argparse
from pathlib import Path
import sys

import generate_unicode as unicode

NAME = "VerticalOrientation.txt"
URL = "https://www.unicode.org/Public/17.0.0/ucd/VerticalOrientation.txt"
SHA256 = "dcef09c3fb24d356b042569c328ec341efc5b53447700d799f2fb4834c3cd3cd"
PROPERTIES = ("R", "U", "Tu", "Tr")


def generate(data):
    ranges = []
    for line in data.decode("utf-8").splitlines():
        content = line.split("#", 1)[0].strip()
        if not content:
            continue
        fields = [field.strip() for field in content.split(";")]
        match = unicode.RANGE.fullmatch(fields[0])
        if len(fields) != 2 or not match or fields[1] not in PROPERTIES:
            raise ValueError("Invalid vertical orientation property data")
        ranges.append((int(match[1], 16), int(match[2] or match[1], 16), PROPERTIES.index(fields[1])))
    ranges = [r for r in unicode.merge_ranges(ranges) if r[2]]
    lines = [
        "/* SPDX-License-Identifier: MIT\n * Generated by tools/generate_vertical.py; do not edit.",
        " * Unicode 17.0.0; Unicode-3.0 license, tests/fixtures/unicode/LICENSE.txt.",
        f" * {URL}", f" * SHA-256: {SHA256}",
        " * Omitted code points have default R (clockwise rotation). */",
        "#ifndef EXR_VERTICAL_DATA_H", "#define EXR_VERTICAL_DATA_H", "#include <stdint.h>",
        "typedef struct { uint32_t first, last; uint8_t value; } exr_vertical_range;", "",
    ]
    lines.extend(unicode.enum_lines("vo", PROPERTIES))
    lines.extend(line.replace("exr_unicode_range", "exr_vertical_range")
                 for line in unicode.table_lines("vo", ranges))
    lines.extend(["#endif /* EXR_VERTICAL_DATA_H */", ""])
    return "\n".join(lines).encode("utf-8"), len(ranges)


def main():
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--download", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    fixture = root / "tests/fixtures/unicode" / NAME
    cache = fixture.parent if fixture.exists() else root / "build/unicode-cache"
    unicode.SOURCES[NAME] = (URL, SHA256)
    data = unicode.source_data(NAME, cache, fixture.parent, args.download)
    header, count = generate(data)
    for path, content in ((root / "src/vertical_data.h", header), (fixture, data)):
        if args.check:
            if not path.exists() or path.read_bytes() != content:
                raise ValueError(f"Generated output differs: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    print(f"Unicode 17 vertical orientation: {count} ranges, {len(header)}-byte header; " +
          ("generated files match." if args.check else "generated files written."))


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError) as error:
        print(f"error: {error}", file=sys.stderr)
        sys.exit(1)
