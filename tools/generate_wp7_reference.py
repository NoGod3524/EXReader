#!/usr/bin/env python3
"""Generate tests/fixtures/wp7/reference.h from fixed HarfBuzz 14.6.0.

Development only: requires uharfbuzz.  The C test consumes the committed
header and neither Python nor HarfBuzz is needed to build or run it.
"""
