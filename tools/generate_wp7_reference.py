from pathlib import Path
import hashlib
import json
import sys

import uharfbuzz as hb

ROOT = Path(__file__).resolve().parents[1]
FIXTURES = ROOT / "tests/fixtures/wp7"
CASES = json.loads((FIXTURES / "cases.json").read_text(encoding="utf-8"))
SCRIPTS = {"beng": "Beng", "taml": "Taml", "telu": "Telu", "knda": "Knda",
           "mlym": "Mlym", "thai": "Thai", "khmr": "Khmr", "mymr": "Mymr"}
FONT_SIZE = 200.0


def c_bytes(data):
    return "".join("\\%03o" % b for b in data)


def shape(font_path, script, text):
    data = font_path.read_bytes()
    face = hb.Face(data)
    font = hb.Font(face)
    font.scale = (face.upem, face.upem)
    buffer = hb.Buffer()
    buffer.add_utf8(text.encode())
    buffer.direction = "ltr"
    buffer.script = SCRIPTS[script]
    buffer.language = "en"
    buffer.flags = hb.BufferFlags.REMOVE_DEFAULT_IGNORABLES
    hb.shape(font, buffer)
    scale = FONT_SIZE / face.upem
    infos = [(i.codepoint, i.cluster, p.x_advance * scale, p.y_advance * scale,
              p.x_offset * scale, p.y_offset * scale)
             for i, p in zip(buffer.glyph_infos, buffer.glyph_positions)]
    starts = sorted({x[1] for x in infos})
    result = []
    for glyph, cluster, ax, ay, x, y in infos:
        end = len(text.encode())
        for start in starts:
            if start > cluster:
                end = start
                break
        result.append((glyph, cluster, end, ax, ay, x, y))
    return result, data


def main():
    rows = ["/* Generated by tools/generate_wp7_reference.py; HarfBuzz " + hb.version_string() + ". */",
            "/* Fonts: Noto Sans OFL 1.1 (unmodified), and original MIT synthetic fonts. */",
            "typedef struct { unsigned glyph; unsigned cluster_start, cluster_end;",
            "  float ax, ay, x, y; } wp7_expected_glyph;",
            "typedef struct { const char *font; const char *script; const char *text;",
            "  size_t size, count; wp7_expected_glyph glyphs[24]; } wp7_case;",
            "static const wp7_case wp7_reference[] = {"]
    total = 0
    for script in SCRIPTS:
        for variant in ("real", "synthetic"):
            name = script + "-" + variant + ".ttf"
            path = FIXTURES / "fonts" / name
            digest = hashlib.sha256(path.read_bytes()).hexdigest()
            rows.append(f'  /* {name} SHA256 {digest} */')
            for text in CASES[script]:
                glyphs, _ = shape(path, script, text)
                assert len(glyphs) <= 24
                values = []
                for glyph, start, end, ax, ay, x, y in glyphs:
                    values.append("{%u,%u,%u,%.4ff,%.4ff,%.4ff,%.4ff}" % (glyph, start, end, ax, ay, x, y))
                data = text.encode()
                rows.append('  {"%s","%s","%s",%u,%u,{%s}},' %
                            (name, script, c_bytes(data), len(data), len(glyphs), ",".join(values)))
                total += 1
    rows.extend(["};", ""])
    (FIXTURES / "reference.h").write_text("\n".join(rows), encoding="utf-8")
    print("Generated %d reference cases with HarfBuzz %s" % (total, hb.version_string()))


if __name__ == "__main__":
    main()
