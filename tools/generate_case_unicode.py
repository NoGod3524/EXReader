import argparse
from array import array
from pathlib import Path
import generate_unicode as shared

shared.SOURCES['SpecialCasing.txt']=(shared.BASE_URL+'SpecialCasing.txt',
    'efc25faf19de21b92c1194c111c932e03d2a5eaf18194e33f1156e96de4c9588')
shared.SOURCES['PropList.txt']=(shared.BASE_URL+'PropList.txt',
    '130dcddcaadaf071008bdfce1e7743e04fdfbc910886f017d9f9ac931d8c64dd')
NAMES=('UnicodeData.txt','SpecialCasing.txt','DerivedCoreProperties.txt','PropList.txt')

def generate(data):
    maps={};props=array('H',[0])*0x110000
    for line in data['UnicodeData.txt'].decode().splitlines():
        f=line.split(';');cp=int(f[0],16);ccc=int(f[3])
        if ccc: props[cp]|=ccc<<6
        if f[2]=='Lt': props[cp]|=8
        lower=(int(f[13],16),) if f[13] else (cp,)
        upper=(int(f[12],16),) if f[12] else (cp,)
        title=(int(f[14],16),) if f[14] else upper
        if (lower,title,upper)!=((cp,),)*3: maps[cp]=(lower,title,upper)
    for line in data['SpecialCasing.txt'].decode().splitlines():
        f=[x.strip() for x in line.split('#')[0].split(';')]
        if len(f)<5 or f[4]: continue
        maps[int(f[0],16)]=tuple(tuple(int(x,16) for x in part.split()) for part in f[1:4])
    for name,wanted in [('DerivedCoreProperties.txt',{'Cased':1,'Uppercase':2,'Lowercase':4,'Case_Ignorable':16}),('PropList.txt',{'Soft_Dotted':32})]:
        for line in data[name].decode().splitlines():
            f=[x.strip() for x in line.split('#')[0].split(';')]
            if len(f)<2 or f[1] not in wanted: continue
            limits=f[0].split('..');first=int(limits[0],16);last=int(limits[-1],16)
            for cp in range(first,last+1): props[cp]|=wanted[f[1]]
    lines=['/* SPDX-License-Identifier: GPL-3.0-only\n * Generated by tools/generate_case_unicode.py; Unicode 17.0.0.',
      ' * Data license: Unicode-3.0; tests/fixtures/unicode/LICENSE.txt.']
    for name in NAMES:
        url,sha=shared.SOURCES[name];lines+=[' * '+url,' * '+sha]
    lines+=[' */','#ifndef EXR_CASE_UNICODE_DATA_H','#define EXR_CASE_UNICODE_DATA_H',
      'typedef struct { uint32_t cp,values[3][3]; unsigned char size[3]; } exr_case_mapping;',
      'static const exr_case_mapping exr_case_mappings[] = {']
    vectors=['# Unicode 17 default full case mappings: scalar;lower;title;upper',
      '# Data license: Unicode-3.0; see LICENSE.txt. Generated by tools/generate_case_unicode.py.']
    for cp,modes in sorted(maps.items()):
        assert all(1<=len(m)<=3 for m in modes)
        fields=['{'+','.join('0x%X'%x for x in m+(0,)*(3-len(m)))+'}' for m in modes]
        lines.append('  {0x%X,{%s},{%s}},'%(cp,','.join(fields),','.join(str(len(m)) for m in modes)))
        vectors.append('%X;'%cp+';'.join(' '.join('%X'%x for x in m) for m in modes))
    lines+=['};','typedef struct { uint32_t first,last; unsigned properties; } exr_case_range;',
      'static const exr_case_range exr_case_properties_data[] = {']
    first=0
    for cp in range(1,len(props)+1):
        if cp==len(props) or props[cp]!=props[first]:
            if props[first]: lines.append('  {0x%X,0x%X,%u},'%(first,cp-1,props[first]))
            first=cp
    lines+=['};','#endif','']
    return '\n'.join(lines).encode(),('\n'.join(vectors)+'\n').encode()

def main():
    root=Path(__file__).resolve().parents[1];parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--download',action='store_true');parser.add_argument('--check',action='store_true')
    parser.add_argument('--cache-dir',type=Path,default=root/'build/unicode-cache');a=parser.parse_args()
    data={n:shared.source_data(n,a.cache_dir,root/'tests/fixtures/unicode',a.download) for n in NAMES}
    header,vectors=generate(data)
    for path,value in [(root/'src/case_unicode_data.h',header),(root/'tests/fixtures/unicode/CaseMappingTest.txt',vectors)]:
        if a.check:
            if not path.exists() or path.read_bytes()!=value: raise ValueError(str(path)+' differs')
        else: path.write_bytes(value)
    print('Unicode 17 case mapping:',len(header),'header bytes;',len(vectors),'vector bytes;', 'verified' if a.check else 'written')
if __name__=='__main__': main()
