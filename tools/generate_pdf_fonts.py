#!/usr/bin/env python3
"""Reproduce pinned PDF font facts; never execute downloaded source.

Normal builds use the committed header. Run with --download to fetch missing
inputs, and --check to verify the generated header and redistribution notices.
"""
# SPDX-License-Identifier: GPL-3.0-only
import argparse
import hashlib
import json
from pathlib import Path
import re
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
ADOBE = 'https://raw.githubusercontent.com/adobe-type-tools/agl-aglfn/4036a9ca80a62f64f9de4f7321a9a045ad0ecfd6/'
PDFJS = 'https://raw.githubusercontent.com/mozilla/pdf.js/81525fd446779f0a29003cf06e3ba33751954826/'
SOURCES = {
    'glyphlist.txt': (ADOBE+'glyphlist.txt', 'a3b2f61ced9f3644cc0d4ecde5c59df34ca286c689d9484a43a710a81c466789'),
    'zapfdingbats.txt': (ADOBE+'zapfdingbats.txt', 'f6394e3cb8a447e84a1dad75d4baaf2aa7f45dc104faf369f4720e1a774ef2dc'),
    'encodings.js': (PDFJS+'src/core/encodings.js', 'eee7b0b49fbf0c27fd1765abeea43621c23da3d1a8a592ad0e5ddfe6743658e3'),
    'metrics.js': (PDFJS+'src/core/metrics.js', 'cb1436885fea32792e4aed5ca45704d392c5edae5ab66b2d9c0625c2c31057d7'),
    'pdfjs-license.txt': (PDFJS+'LICENSE', '0d542e0c8804e39aa7f37eb00da5a762149dc682d7829451287e11b938e94594'),
}


def generate(data):
    maps = []
    for filename in ('glyphlist.txt', 'zapfdingbats.txt'):
        mapping = {}
        for line in data[filename].splitlines():
            if not line or line.startswith('#'):
                continue
            name, values = line.split(';')
            assert name not in mapping
            mapping[name] = tuple(int(v, 16) for v in values.split())
        maps.append(mapping)
    encodings = {}
    for name, values in re.findall(r'const (\w+) = \[([^\]]+)\];', data['encodings.js']):
        encodings[name] = json.loads('['+values+']')
        assert len(encodings[name]) == 256
    assert len(encodings) == 7
    metrics = {}
    for name1, name2, body in re.findall(r't(?:\.(\w+)|\["([^"]+)"\]) = getLookupTableFactory\(function \(t\) \{(.*?)\}\);', data['metrics.js'], re.S):
        items = re.findall(r't\.(\w+) = (\d+);', body)
        metrics[name1 or name2] = {name: int(width) for name, width in items}
        assert len(items) == len(metrics[name1 or name2]) and items
    assert len(metrics) == 10
    names = sorted(set().union(*maps, *(set(e) for e in encodings.values()), *(set(m) for m in metrics.values())))
    ids = {name: i for i, name in enumerate(names)}
    offsets, pool_size = {}, 0
    for name in names:
        offsets[name] = pool_size
        pool_size += len(name)+1
    assert pool_size < 65536 and len(names) < 65536
    out = ['/* Generated by tools/generate_pdf_fonts.py. Do not edit.',
           ' * Glyph facts: Copyright 2002-2019 Adobe, BSD-3-Clause.',
           ' * Encoding/metric facts: Copyright 2012 Mozilla Foundation, Apache-2.0.',
           ' * Complete notices: licenses/adobe-glyph-list.txt and pdfjs.txt. */',
           'static const char pdf_glyph_names[] =']
    # Separate arrays avoid the C99 4095-character minimum string-literal limit.
    # Each name is represented in a byte initializer instead of one huge literal.
    out[-1] = 'static const char pdf_glyph_names[] = {'
    raw = b''.join(n.encode('ascii')+b'\0' for n in names)
    for at in range(0, len(raw), 24):
        out.append('  '+','.join(str(b) for b in raw[at:at+24])+',')
    out.append('};')

    def array(ctype, name, rows):
        out.append(f'static const {ctype} {name}[] = {{')
        out.extend('  '+row+',' for row in rows)
        out.append('};')

    array('uint16_t', 'pdf_glyph_offsets', [str(offsets[n]) for n in names])
    scalars = []
    for table, mapping in zip(('agl', 'dingbats'), maps):
        rows = []
        for name in sorted(mapping):
            values = mapping[name]
            rows.append('{%d,%d,%d}' % (ids[name], len(scalars), len(values)))
            scalars.extend(values)
        array('pdf_name_mapping', 'pdf_'+table, rows)
    assert len(scalars) < 65536
    array('uint32_t', 'pdf_name_scalars', [hex(v) for v in scalars])
    for name, values in sorted(encodings.items()):
        array('uint16_t', 'pdf_'+name, [str(ids[n]) for n in values])
    array('pdf_encoding_vector', 'pdf_encodings', ['{"%s",pdf_%s}' % (n, n) for n in sorted(encodings)])
    for name, widths in sorted(metrics.items()):
        array('pdf_width_entry', 'pdf_widths_'+name.replace('-', '_'), ['{%d,%d}' % (ids[n], widths[n]) for n in sorted(widths)])
    array('pdf_standard_metrics', 'pdf_metrics', ['{"%s",pdf_widths_%s,%d}' % (n, n.replace('-', '_'), len(m)) for n, m in sorted(metrics.items())])
    notice = data['glyphlist.txt'].split('# -----------------------------------------------------------')[1]
    notice = '\n'.join(line.removeprefix('# ').removeprefix('#') for line in notice.strip().splitlines()).strip()+'\n'
    return {
        ROOT/'src/pdf_font_data.h': '\n'.join(out)+'\n',
        ROOT/'licenses/adobe-glyph-list.txt': notice,
        ROOT/'licenses/pdfjs.txt': 'Copyright 2012 Mozilla Foundation\n\n'+data['pdfjs-license.txt'],
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--download', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    cache = ROOT/'build/pdf-font-data'
    cache.mkdir(parents=True, exist_ok=True)
    data = {}
    for filename, (url, digest) in SOURCES.items():
        path = cache/filename
        if not path.exists() and args.download:
            with urllib.request.urlopen(url, timeout=60) as source:
                path.write_bytes(source.read())
        content = path.read_bytes()
        if hashlib.sha256(content).hexdigest() != digest:
            raise ValueError('SHA256 mismatch: '+filename)
        data[filename] = content.decode('utf-8')
    for path, content in generate(data).items():
        raw = content.encode('utf-8')
        if args.check:
            if path.read_bytes() != raw:
                raise ValueError('Generated output differs: '+str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(raw)
    print('PDF font tables and notices verified' if args.check else 'PDF font tables and notices generated')


if __name__ == '__main__':
    main()
