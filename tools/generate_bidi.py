#!/usr/bin/env python3
"""Generate pinned Unicode 17 bidi tables and complete conformance fixtures.

Normal C builds use committed data and need neither Python nor network access.
Run: python tools/generate_bidi.py --download [--check]
"""
# SPDX-License-Identifier: MIT
import argparse
import hashlib
from pathlib import Path
import re
import sys
import urllib.request

VERSION = "17.0.0"
BASE = f"https://www.unicode.org/Public/{VERSION}/ucd/"
SOURCES = {
    "DerivedBidiClass.txt": (BASE + "extracted/DerivedBidiClass.txt", "4867b4b7f0731ed1bfcd34cc6251211ff1542541fce0734b6fbda139ee80b3a4"),
    "BidiBrackets.txt": (BASE + "BidiBrackets.txt", "dadbaf38a0d0246e5b805bf8725cb81b7c621f93d030595635f5ba2c2f179428"),
    "BidiMirroring.txt": (BASE + "BidiMirroring.txt", "a2f16fb873ab4fcdf3221cb1a8a85a134ddd6ed03603181823ff5206af3741ce"),
    "BidiTest.txt": (BASE + "BidiTest.txt", "888bdfc8090652272d1f859cdb00ae659e2dc6c26740be61ef1d03998a687620"),
    "BidiCharacterTest.txt": (BASE + "BidiCharacterTest.txt", "a3e6e905ab5afbe318a96df5401d0372a04cd73ef139ab5e3cf0ae241c255488"),
}
CLASSES = ("L", "R", "AL", "EN", "ES", "ET", "AN", "CS", "NSM", "BN", "B", "S", "WS", "ON", "LRE", "LRO", "RLE", "RLO", "PDF", "LRI", "RLI", "FSI", "PDI")
LONG = {"Left_To_Right": "L", "Right_To_Left": "R", "Arabic_Letter": "AL", "European_Terminator": "ET"}
RANGE = re.compile(r"([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\Z")


def read_source(name, cache, fixtures, download):
    path = fixtures / name if name in ("BidiTest.txt", "BidiCharacterTest.txt") and (fixtures / name).exists() else cache / name
    if path.exists():
        data = path.read_bytes()
    elif download:
        with urllib.request.urlopen(SOURCES[name][0], timeout=60) as response:
            data = response.read()
    else:
        raise ValueError(f"missing {path}; run with --download")
    if hashlib.sha256(data).hexdigest() != SOURCES[name][1]:
        raise ValueError(f"SHA-256 mismatch: {name}")
    if not path.exists():
        cache.mkdir(parents=True, exist_ok=True)
        (cache / name).write_bytes(data)
    return data


def interval(value):
    m = RANGE.fullmatch(value)
    if not m:
        raise ValueError(f"invalid range: {value}")
    first, last = int(m[1], 16), int(m[2] or m[1], 16)
    if not 0 <= first <= last <= 0x10ffff:
        raise ValueError("range outside Unicode")
    return first, last


def generate(data):
    values = bytearray(0x110000)
    lines = data["DerivedBidiClass.txt"].decode("utf-8").splitlines()
    # @missing declarations are ordered: narrower defaults override the global L.
    for line in lines:
        if "@missing:" in line:
            span, prop = [s.strip() for s in line.split("@missing:", 1)[1].split(";")]
            first, last = interval(span)
            values[first:last + 1] = bytes([CLASSES.index(LONG.get(prop, prop))]) * (last - first + 1)
    seen = bytearray(0x110000)
    for line in lines:
        content = line.split("#", 1)[0].strip()
        if content:
            span, prop = [s.strip() for s in content.split(";")]
            first, last = interval(span)
            if any(seen[first:last + 1]):
                raise ValueError("overlapping explicit Bidi_Class ranges")
            seen[first:last + 1] = b"\1" * (last - first + 1)
            values[first:last + 1] = bytes([CLASSES.index(prop)]) * (last - first + 1)
    ranges = []
    first = 0
    for cp in range(1, 0x110001):
        if cp == 0x110000 or values[cp] != values[first]:
            if values[first]:
                ranges.append((first, cp - 1, values[first]))
            first = cp
    brackets, mirrors = [], []
    for name, target in (("BidiBrackets.txt", brackets), ("BidiMirroring.txt", mirrors)):
        for line in data[name].decode("utf-8").splitlines():
            content = line.split("#", 1)[0].strip()
            if not content:
                continue
            fields = [s.strip() for s in content.split(";")]
            cp, pair = int(fields[0], 16), int(fields[1], 16)
            if not 0 <= cp <= 0x10ffff or not 0 <= pair <= 0x10ffff or (target and cp <= target[-1][0]):
                raise ValueError(f"invalid or unordered {name}")
            if name == "BidiBrackets.txt":
                if fields[2] not in ("o", "c"):
                    raise ValueError("invalid bracket type")
                target.append((cp, pair, 1 if fields[2] == "o" else 2))
            else:
                target.append((cp, pair))
    output = ["/* SPDX-License-Identifier: MIT\n * Generated by tools/generate_bidi.py; do not edit.",
              " * Unicode 17.0.0; Unicode-3.0 data license.",
              " * Copyright (c) 1991-2026 Unicode, Inc.",
              " * See tests/fixtures/unicode/LICENSE.txt.",
              " * Pinned sources and SHA-256:"]
    for name, (url, sha) in SOURCES.items():
        output += [f" * {url}", f" * {sha}"]
    output += [" */", "#ifndef EXR_BIDI_DATA_H", "#define EXR_BIDI_DATA_H", "enum exr_bidi_type {"]
    output += [f"  bidi_{name} = {i}," for i, name in enumerate(CLASSES)]
    output += ["};", "typedef struct { uint32_t first, last; unsigned char type; } bidi_range;",
               "static const bidi_range bidi_ranges[] = {"]
    output += ["  " + "".join(f"{{0x{a:X},0x{b:X},{v}}}," for a, b, v in ranges[i:i + 4]) for i in range(0, len(ranges), 4)]
    output += ["};", "typedef struct { uint32_t codepoint, pair; unsigned char kind; } bidi_bracket;",
               "static const bidi_bracket bidi_brackets[] = {"]
    output += [f"  {{0x{cp:X},0x{pair:X},{kind}}}," for cp, pair, kind in brackets]
    output += ["};", "typedef struct { uint32_t codepoint, mirror; } bidi_mirror;",
               "static const bidi_mirror bidi_mirrors[] = {"]
    output += [f"  {{0x{cp:X},0x{pair:X}}}," for cp, pair in mirrors]
    output += ["};", "#endif", ""]
    return "\n".join(output).encode("utf-8")


def main():
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument("--download", action="store_true")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--cache-dir", type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    cache = args.cache_dir or root / "build/bidi-cache"
    fixtures = root / "tests/fixtures/bidi"
    data = {name: read_source(name, cache, fixtures, args.download) for name in SOURCES}
    outputs = {root / "src/bidi_data.h": generate(data)}
    outputs.update({fixtures / name: data[name] for name in ("BidiTest.txt", "BidiCharacterTest.txt")})
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_bytes() != content:
                raise ValueError(f"generated output differs: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    print("Unicode 17 bidi tables and complete conformance fixtures " + ("verified" if args.check else "generated"))


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError) as error:
        sys.exit(str(error))
