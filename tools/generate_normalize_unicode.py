import argparse
from pathlib import Path
import generate_unicode as shared
shared.SOURCES['CompositionExclusions.txt']=(shared.BASE_URL+'CompositionExclusions.txt',
    '2f239196ef3b5b61db5cc476e9bd80f534d15aa1b74e1be1dea5d042a344c85f')
shared.SOURCES['NormalizationTest.txt']=(shared.BASE_URL+'NormalizationTest.txt',
    '5019ffd530751a741900c849c0e010332f142a3612234639bd200b82138a87db')


def generate(data,exclusions):
    decompositions={};ccc={}
    for line in data.decode().splitlines():
        fields=line.split(';');cp=int(fields[0],16)
        if int(fields[3]): ccc[cp]=int(fields[3])
        if fields[5] and not fields[5].startswith('<'):
            decompositions[cp]=tuple(int(x,16) for x in fields[5].split())
    excluded={int(line.split('#')[0].strip(),16) for line in exclusions.decode().splitlines() if line.split('#')[0].strip()}
    def expand(cp):
        if cp not in decompositions: return (cp,)
        return sum((expand(x) for x in decompositions[cp]),())
    expanded={cp:expand(cp) for cp in decompositions}
    assert max(map(len,expanded.values()))==4
    # Full composition exclusion also excludes singletons and nonstarter decompositions.
    pairs=sorted((parts[0],parts[1],cp) for cp,parts in decompositions.items()
        if cp not in excluded and len(parts)==2 and ccc.get(parts[0],0)==0)
    assert len({(a,b) for a,b,_ in pairs})==len(pairs)
    combining=shared.merge_ranges((cp,cp,value) for cp,value in sorted(ccc.items()))
    lines=['/* SPDX-License-Identifier: GPL-3.0-only\n * Generated by tools/generate_normalize_unicode.py; Unicode 17.0.0.',
      ' * Data license: Unicode-3.0; see tests/fixtures/unicode/LICENSE.txt.']
    for name in ('UnicodeData.txt','CompositionExclusions.txt'):
        url,sha=shared.SOURCES[name];lines+=[' * '+url,' * '+sha]
    lines+=[' */','#ifndef EXR_NORMALIZE_DATA_H','#define EXR_NORMALIZE_DATA_H','#include <stdint.h>']
    lines+=['static const struct { uint32_t cp,parts[4]; unsigned length; } exr_canonical_decompositions[] = {']
    for cp,parts in sorted(expanded.items()):
        lines.append('  {0x%X,{%s},%u},'%(cp,','.join('0x%X'%x for x in parts+(0,)*(4-len(parts))),len(parts)))
    lines+=['};','static const struct { uint32_t first,last; unsigned value; } exr_canonical_classes[] = {']
    lines+=['  {0x%X,0x%X,%u},'%row for row in combining]
    lines+=['};','static const struct { uint32_t first,second,result; } exr_canonical_compositions[] = {']
    lines+=['  {0x%X,0x%X,0x%X},'%row for row in pairs]
    lines+=['};','#endif','']
    return '\n'.join(lines).encode()


def main():
    root=Path(__file__).resolve().parents[1];p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--download',action='store_true');p.add_argument('--check',action='store_true')
    p.add_argument('--cache-dir',type=Path,default=root/'build/unicode-cache');a=p.parse_args()
    files={n:shared.source_data(n,a.cache_dir,root/'tests/fixtures/unicode',a.download)
        for n in ('UnicodeData.txt','CompositionExclusions.txt','NormalizationTest.txt')}
    outputs={root/'src/normalize_data.h':generate(files['UnicodeData.txt'],files['CompositionExclusions.txt']),
        root/'tests/fixtures/unicode/NormalizationTest.txt':files['NormalizationTest.txt']}
    for path,data in outputs.items():
        if a.check:
            if not path.exists() or path.read_bytes()!=data: raise ValueError('generated file differs: '+str(path))
        else: path.write_bytes(data)
        print(path.name,len(data),'bytes;', 'verified' if a.check else 'written')
if __name__=='__main__': main()
