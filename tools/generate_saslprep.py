"""Generate RFC 4013 / Unicode 3.2 tables with Python's frozen UCD.

Development tool only; no runtime Python/Unicode library dependency.
"""
from pathlib import Path
import stringprep as s
from unicodedata import ucd_3_2_0 as u

root = Path(__file__).resolve().parents[1]
decomp, scalars, compose, combining, flags = [], [], [], [], []
checks = [s.in_table_c12, s.in_table_c21, s.in_table_c22, s.in_table_c3,
          s.in_table_c4, s.in_table_c5, s.in_table_c6, s.in_table_c7,
          s.in_table_c8, s.in_table_c9, s.in_table_a1]
for cp in range(0x110000):
    c = chr(cp)
    flag = (1 if s.in_table_b1(c) else 0) | (2 if s.in_table_c12(c) else 0)
    flag |= 4 if any(f(c) for f in checks) else 0
    flag |= 8 if s.in_table_d1(c) else 0
    flag |= 16 if s.in_table_d2(c) else 0
    if flag:
        if flags and flags[-1][1] + 1 == cp and flags[-1][2] == flag:
            flags[-1] = (flags[-1][0], cp, flag)
        else:
            flags.append((cp, cp, flag))
    if 0xAC00 <= cp <= 0xD7A3:
        continue
    n = u.normalize('NFKD', c)
    if n != c:
        decomp.append((cp, len(scalars), len(n)))
        scalars.extend(map(ord, n))
    cc = u.combining(c)
    if cc:
        combining.append((cp, cc))
    d = u.decomposition(c)
    if d and not d.startswith('<'):
        parts = tuple(int(x, 16) for x in d.split())
        if len(parts) == 2 and u.normalize('NFC', ''.join(map(chr, parts))) == c:
            compose.append((*parts, cp))
compose.sort()
lines = ['/* SPDX-License-Identifier: GPL-3.0-only\n * Generated by tools/generate_saslprep.py; Unicode 3.2 / RFC 4013.',
         '   Data license: Unicode-3.0 (see tests/fixtures/unicode/LICENSE.txt). */']
def table(name, declaration, rows):
    lines.append(f'static const {declaration} {name}[]={{')
    lines.extend('  {' + ','.join(hex(v) for v in row) + '},' for row in rows)
    lines.append('};')
table('prep_flags', 'struct { uint32_t first,last; unsigned flags; }', flags)
table('prep_decomp', 'struct { uint32_t cp,offset,length; }', decomp)
lines.append('static const uint32_t prep_scalars[]={')
for i in range(0, len(scalars), 12):
    lines.append('  ' + ','.join(hex(v) for v in scalars[i:i+12]) + ',')
lines.append('};')
table('prep_combining', 'struct { uint32_t cp; unsigned value; }', combining)
table('prep_compose', 'struct { uint32_t first,second,result; }', compose)
target = root/'src/pdf_saslprep_data.h'
target.write_text('\n'.join(lines)+'\n', encoding='utf-8')
print(target.name, target.stat().st_size, 'bytes')
