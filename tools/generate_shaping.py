import argparse
import hashlib
import sys
from pathlib import Path
from urllib.request import urlopen

SOURCES = {
    "extracted/DerivedJoiningType.txt": "f39ebe974825d6736aee15582250307aa532b2cfab3caf3f86bd23fddc9c5c4d",
    "Scripts.txt": "9f5e50d3abaee7d6ce09480f325c706f485ae3240912527e651954d2d6b035bf",
}


def ranges(text, values):
    result = []
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        interval, prop = (x.strip() for x in line.split(";"))
        if prop not in values:
            continue
        bounds = interval.split("..")
        first, last = int(bounds[0], 16), int(bounds[-1], 16)
        assert 0 <= first <= last <= 0x10FFFF
        result.append((first, last, values[prop]))
    result.sort()
    merged = []
    for first, last, value in result:
        assert not merged or first > merged[-1][1]
        if merged and first == merged[-1][1] + 1 and value == merged[-1][2]:
            merged[-1] = (merged[-1][0], last, value)
        else:
            merged.append((first, last, value))
    return merged


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--download", action="store_true")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--cache-dir", type=Path, default=Path("build/shaping-cache"))
    args = parser.parse_args()
    texts = {}
    for name, digest in SOURCES.items():
        cached = args.cache_dir / name
        if args.download and not cached.is_file():
            data = urlopen("https://www.unicode.org/Public/17.0.0/ucd/" + name, timeout=30).read()
            if hashlib.sha256(data).hexdigest() != digest:
                raise ValueError("Unicode download hash mismatch: " + name)
            cached.parent.mkdir(parents=True, exist_ok=True)
            cached.write_bytes(data)
        data = cached.read_bytes()
        if hashlib.sha256(data).hexdigest() != digest:
            raise ValueError("Unicode source hash mismatch: " + name)
        texts[name] = data.decode("utf-8")
    joining = ranges(texts["extracted/DerivedJoiningType.txt"], {"R": 1, "L": 2, "D": 3, "C": 4, "T": 5})
    scripts = ranges(texts["Scripts.txt"], {"Latin": 1, "Arabic": 2})
    lines = ["/* Unicode 17.0.0 data, Unicode-3.0; generated by tools/generate_shaping.py. */",
             "#ifndef EXR_SHAPING_DATA_H", "#define EXR_SHAPING_DATA_H", "#include <stdint.h>",
             "typedef struct { uint32_t first, last; unsigned char value; } exr_shape_range;"]
    for name, records in (("joining", joining), ("script", scripts)):
        lines.append("static const exr_shape_range exr_shape_" + name + "[] = {")
        lines.extend(f"  {{0x{a:X}, 0x{b:X}, {v}}}," for a, b, v in records)
        lines.append("};")
    lines.extend(("#endif", ""))
    generated = "\n".join(lines)
    output = Path(__file__).resolve().parents[1] / "src/shaping_data.h"
    if args.check:
        if output.read_text(encoding="utf-8") != generated:
            raise ValueError("shaping_data.h differs from pinned sources")
    else:
        output.write_text(generated, encoding="utf-8")
    print(f"Unicode shaping data verified: {len(joining)} joining, {len(scripts)} script ranges")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, AssertionError) as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
