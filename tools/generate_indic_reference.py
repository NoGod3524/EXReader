#!/usr/bin/env python3
"""Regenerate independent HarfBuzz expectations for the original Indic fonts.
Development only: requires uharfbuzz; the native engine and tests do not use it.
"""
# SPDX-License-Identifier: MIT
from pathlib import Path
import hashlib
import uharfbuzz as hb
ROOT = Path(__file__).resolve().parents[1]/'tests/fixtures/indic'
CASES = ['क', 'कि', 'क्त', 'र्क', 'र्कि', 'क्ष', 'ज्ञ', 'क़', 'क़', 'क्र', 'क्य', 'क्ह', 'क्\u200dत', 'क्\u200cत', 'र्\u200dक', 'र्\u200cक', 'किं', 'ि', '्', '़', 'ं', 'क़्त', 'कि र्कु', 'का', 'को', 'के', 'क॑', 'ग्त', 'क्क्कि', 'क्रि', 'क्यि', 'क्हि']

def main():
    rows = ['/* Generated by tools/generate_indic_reference.py; HarfBuzz '+hb.version_string()+'. */',
            'typedef struct { unsigned glyph; float ax,ay,x,y; } indic_expected;',
            'typedef struct { const char *font,*text; size_t count; indic_expected glyphs[16]; } indic_reference;',
            'static const indic_reference reference[] = {']
    for name in ['dev2.ttf','deva-legacy.ttf']:
        data=(ROOT/name).read_bytes()
        rows.append('  /* '+name+' SHA256 '+hashlib.sha256(data).hexdigest()+' */')
        face=hb.Face(data); font=hb.Font(face); font.scale=(face.upem,face.upem)
        for text in CASES:
            buffer=hb.Buffer(); buffer.add_utf8(text.encode()); buffer.guess_segment_properties()
            buffer.flags=hb.BufferFlags.REMOVE_DEFAULT_IGNORABLES
            hb.shape(font,buffer)
            values=[]
            for glyph,p in zip(buffer.glyph_infos,buffer.glyph_positions):
                floats=','.join(format(v*100/face.upem,'.9f')+'f' for v in [p.x_advance,p.y_advance,p.x_offset,p.y_offset])
                values.append('{'+str(glyph.codepoint)+','+floats+'}')
            assert len(values)<=16
            encoded=''.join('\\x%02x'%b for b in text.encode())
            rows.append('  {"'+name+'","'+encoded+'",'+str(len(values))+',{'+','.join(values)+'}},')
    rows.extend(['};',''])
    (ROOT/'reference.h').write_text('\n'.join(rows),encoding='utf-8')
    print('Generated '+str(len(CASES)*2)+' independent Devanagari reference cases')

if __name__=='__main__': main()
