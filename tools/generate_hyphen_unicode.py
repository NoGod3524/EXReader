import argparse
from pathlib import Path
import generate_unicode as shared

shared.SOURCES['CaseFolding.txt']=(shared.BASE_URL+'CaseFolding.txt',
    'ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183')

def generate(data,unicode):
    mapping={}
    for line in data.decode('utf-8').splitlines():
        fields=line.split('#')[0].split(';')
        if len(fields)<3 or fields[1].strip() not in ('C','F'): continue
        key=int(fields[0],16); values=[int(x,16) for x in fields[2].split()]
        if not 1<=len(values)<=3: raise ValueError('unexpected folding length')
        mapping[key]=values
    canonical={}
    for line in unicode.decode('utf-8').splitlines():
        fields=line.split(';')
        if fields[5] and not fields[5].startswith('<'):
            canonical[int(fields[0],16)]=tuple(int(x,16) for x in fields[5].split())
    def nfd_length(cp):
        if 0xac00<=cp<=0xd7a3: return 3 if (cp-0xac00)%28 else 2
        return sum(nfd_length(x) for x in canonical[cp]) if cp in canonical else 1
    assert max(nfd_length(cp) for cp in canonical)==4
    assert all(sum(nfd_length(x) for x in parts)<=3*nfd_length(cp) for cp,parts in mapping.items())
    ranges=[]; first=None
    for line in unicode.decode('utf-8').splitlines():
        fields=line.split(';'); cp=int(fields[0],16); value=1 if fields[2].startswith('L') else 2 if fields[2].startswith('M') else 3 if fields[2].startswith('N') else 0
        if fields[1].endswith(', First>'): first=cp
        elif fields[1].endswith(', Last>'):
            if first is None: raise ValueError('unpaired Unicode range')
            if value: ranges.append((first,cp,value))
            first=None
        elif value: ranges.append((cp,cp,value))
    ranges=shared.merge_ranges(ranges)
    lines=['/* SPDX-License-Identifier: GPL-3.0-only\n * Generated by tools/generate_hyphen_unicode.py; Unicode 17.0.0.',
      ' * Data license: Unicode-3.0; see tests/fixtures/unicode/LICENSE.txt.',
      ' * Sources/SHA-256:']
    for name in ('CaseFolding.txt','UnicodeData.txt'):
        url,sha=shared.SOURCES[name]; lines += [' * '+url,' * '+sha]
    lines+=[' */','#ifndef EXR_HYPHEN_UNICODE_DATA_H','#define EXR_HYPHEN_UNICODE_DATA_H',
      '#include <stdint.h>','#define EXR_CANONICAL_FOLD_FACTOR 12u /* NFD <=4x; folded NFD <=3x its input NFD. */','typedef struct { uint32_t cp,values[3]; unsigned count; } exr_case_fold;',
      'static const exr_case_fold exr_case_folds[] = {']
    for key,values in sorted(mapping.items()):
        lines.append('  {0x%X,{%s},%u},'%(key,','.join('0x%X'%v for v in values+[0]*(3-len(values))),len(values)))
    lines+=['};','typedef struct { uint32_t first,last; unsigned kind; } exr_word_range;',
      'static const exr_word_range exr_word_ranges[] = {']
    lines += ['  {0x%X,0x%X,%u},'%r for r in ranges]
    lines+=['};','#endif','']
    return '\n'.join(lines).encode()

def main():
    root=Path(__file__).resolve().parents[1]; parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--download',action='store_true');parser.add_argument('--check',action='store_true')
    parser.add_argument('--cache-dir',type=Path,default=root/'build/unicode-cache');a=parser.parse_args()
    data={name:shared.source_data(name,a.cache_dir,root/'tests/fixtures/unicode',a.download) for name in ('CaseFolding.txt','UnicodeData.txt')}
    output=generate(data['CaseFolding.txt'],data['UnicodeData.txt']);p=root/'src/hyphen_unicode_data.h'
    if a.check:
        if not p.exists() or p.read_bytes()!=output: raise ValueError('generated hyphenation Unicode data differs')
    else: p.write_bytes(output)
    print('Unicode 17 hyphenation tables:',len(output),'bytes;','verified' if a.check else 'written')
if __name__=='__main__': main()
